def test_the_reader_calls_no_model_and_opens_no_socket(monkeypatch):
    import socket

    import forecast_brief

    def _refuse(*_args, **_kwargs):  # pragma: no cover - the point is it is not hit
        raise AssertionError("the forecast reader is deterministic; it fetches nothing")

    monkeypatch.setattr(socket.socket, "connect", _refuse)
    monkeypatch.setattr(socket, "create_connection", _refuse)
    assert forecast_brief.parse(_fixture_text()).title_date == FIXTURE_SESSION


