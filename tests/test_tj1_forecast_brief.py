"""TJ-1 item 5 - "Paste daily forecast…": the reader, and the per-session write.

Two halves, both RED before the builder starts:

* ``scripts/forecast_brief.py`` - a deterministic, heading-matched reader over the
  brief the trader's scheduled ChatGPT prompt produces. The golden input is the
  one they actually pasted on 2026-09-17,
  ``tests/fixtures/day_review/forecast_2026-09-17.md``. **Heading match only, no
  model, no guessing:** anything the document does not say is empty, never
  inferred.
* ``MarketJournalService.import_daily_forecast`` - the forecast is filed against
  the SESSION it is about (not a week), and a second paste for the same session
  SUPERSEDES the first, so the page's External forecast block shows one.

Nothing here reads the forecast during the session except the page's own block:
these tests exercise the reader and the writer, never a detector, score or alert.
"""

from __future__ import annotations

import dataclasses
import sys
from pathlib import Path

import pytest

ROOT_DIR = Path(__file__).resolve().parents[1]
SCRIPTS_DIR = ROOT_DIR / "scripts"
if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))

FIXTURE = Path(__file__).resolve().parent / "fixtures" / "day_review" / "forecast_2026-09-17.md"

#: The session the fixture brief is about, from its own first heading
#: ("Thursday, September 17, 2026"). Never from the clock.
FIXTURE_SESSION = "2026-09-17"

#: The two Intraday-playbook paragraphs, verbatim from the fixture. Pinned by
#: hand from the file the trader pasted - not generated by the reader.
BULLISH_PARAGRAPH = (
    "The **bullish continuation** requires the 10-year to remain below 5%, Brent "
    "to stay below roughly $104 and NVDA/SMH to hold their opening strength. If "
    "IWM and banks participate, the rally becomes much healthier because it is no "
    "longer simply another mega-cap squeeze."
)
BEARISH_PARAGRAPH = (
    "The **bearish reversal** is equally clear: Brent snaps back above $105, the "
    "10-year retakes 5%, and semiconductors lose VWAP. If all three happen "
    "together, I would treat today's gap higher as a relief rally that failed "
    "rather than chase dip buys."
)
#: The third paragraph of the same section. It belongs to NEITHER field: a reader
#: that returns "the section" rather than "the two paragraphs" fails here.
SCHEDULE_PARAGRAPH_FRAGMENT = "pending-home-sales data provide the next scheduled"


def _fixture_text() -> str:
    """The brief as a Qt paste would deliver it: newlines translated."""
    return FIXTURE.read_text(encoding="utf-8")


def _fixture_text_crlf() -> str:
    """The same brief with Windows line endings.

    Built rather than read, so the test does not depend on how git checked the
    file out. A reader that splits on ``"\\n\\n"`` without normalising sees one
    paragraph where this text has two.
    """
    return _fixture_text().replace("\r\n", "\n").replace("\n", "\r\n")


# ---------------------------------------------------------------------------
# 0. the fixture itself
# ---------------------------------------------------------------------------
def test_the_fixture_is_the_brief_the_trader_pasted():
    """Guard, not a packet item: the golden input has not been edited away."""
    text = _fixture_text()
    assert text.startswith("# Market Morning Brief")
    assert "Thursday, September 17, 2026" in text
    assert "## Intraday playbook" in text
    assert "### Bottom line" in text
    assert "\r\n" in _fixture_text_crlf(), "the fixture is a Windows-newline file"


