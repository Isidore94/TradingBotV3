def test_the_brief_is_a_frozen_dataclass_nothing_can_edit_after_the_parse():
    import forecast_brief

    brief = forecast_brief.parse(_fixture_text())
    assert dataclasses.is_dataclass(brief)
    with pytest.raises(dataclasses.FrozenInstanceError):
        brief.title_date = "2026-01-01"  # type: ignore[misc]


def test_the_title_date_comes_from_the_first_heading_and_not_the_clock():
    import forecast_brief

    assert forecast_brief.parse(_fixture_text()).title_date == FIXTURE_SESSION


def test_the_two_playbook_paragraphs_are_read_whole_and_kept_apart():
    import forecast_brief

    brief = forecast_brief.parse(_fixture_text())
    assert brief.playbook_bullish == BULLISH_PARAGRAPH
    assert brief.playbook_bearish == BEARISH_PARAGRAPH
    # The section has a THIRD paragraph. It is neither condition.
    assert SCHEDULE_PARAGRAPH_FRAGMENT not in brief.playbook_bullish
    assert SCHEDULE_PARAGRAPH_FRAGMENT not in brief.playbook_bearish


def test_the_ranked_signals_line_is_split_on_the_arrow_in_the_order_written():
    """Five signals, first `10-year yield`. A set would lose the ranking."""
    import forecast_brief

    signals = tuple(forecast_brief.parse(_fixture_text()).ranked_signals)
    assert len(signals) == 5, signals
    assert signals[:4] == ("10-year yield", "Brent", "NVDA/SMH", "breadth")
    assert signals[4].startswith("USD/JPY")


def test_every_turbulence_score_is_an_int_in_document_order():
    """`~8/10 through tomorrow, then ... 6–7/10` is three numbers: 8, 6, 7.

    The two-week line says "around September 29–30" and carries NO `/10`, so
    29 and 30 are not turbulence scores. A reader that scrapes every number on
    a Turbulence line fails here.
    """
    import forecast_brief

    scores = tuple(forecast_brief.parse(_fixture_text()).turbulence)
    assert scores == (8, 6, 7), scores
    assert all(type(value) is int for value in scores), scores


def test_the_bottom_line_is_its_own_section_and_borrows_nothing_from_above():
    import forecast_brief

    body = forecast_brief.parse(_fixture_text()).bottom_line
    assert "Today's setup has improved materially" in body
    assert "10-year yield → Brent" in body
    # The sections above it stay above it.
    assert "Turbulence" not in body
    assert "September 29" not in body
    assert "pending-home-sales" not in body


def test_windows_line_endings_parse_to_the_same_brief():
    import forecast_brief

    assert forecast_brief.parse(_fixture_text_crlf()) == forecast_brief.parse(_fixture_text())


def test_the_source_hash_is_stable_for_one_text_and_moves_with_it():
    import forecast_brief

    text = _fixture_text()
    first = forecast_brief.parse(text).source_hash
    assert first, "a stored forecast needs an identity"
    assert forecast_brief.parse(text).source_hash == first
    assert forecast_brief.parse(text + "\n\nOne more sentence.").source_hash != first


