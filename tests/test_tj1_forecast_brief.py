@pytest.fixture()
def journal(tmp_path, monkeypatch):
    """A MarketJournalService over a temp ledger and a temp thesis sidecar."""
    pytest.importorskip("PySide6", reason="the journal service is a QObject")
    import project_paths

    theses = tmp_path / "market_theses.jsonl"
    monkeypatch.setattr(project_paths, "RUNTIME_DATA_DIR", tmp_path, raising=False)
    monkeypatch.setattr(project_paths, "MARKET_THESES_FILE", theses, raising=False)

    from ui.services.market_journal_service import MarketJournalService

    service = MarketJournalService()
    yield service, theses


def _forecast_rows(path: Path) -> list[dict]:
    import market_thesis

    return [
        row
        for row in market_thesis.read_rows(path)
        if str(row.get("kind") or "") == market_thesis.KIND_FORECAST
    ]


def test_a_pasted_brief_is_filed_against_the_session_it_is_about(journal):
    """The trader may paste at 08:45 for today, or at 21:00 for today. The
    entry's session is the SESSION ARGUMENT, never the paste moment."""
    import market_journal

    service, theses = journal
    result = service.import_daily_forecast(
        text=_fixture_text(),
        target_session=FIXTURE_SESSION,
        source_model="chatgpt",
    )

    assert result.get("ok"), result
    entry = result["entry"]
    assert entry["session_date"] == FIXTURE_SESSION
    assert entry["origin"] == market_journal.ORIGIN_EXTERNAL_FORECAST
    assert entry["timeframe"] == market_journal.TIMEFRAME_D1
    # Stored whole: the reader is a view over the text, never a replacement.
    assert entry["text"].strip() == _fixture_text().strip()


def test_the_sidecar_names_the_target_session_and_the_source_model(journal):
    service, theses = journal
    service.import_daily_forecast(
        text=_fixture_text(),
        target_session=FIXTURE_SESSION,
        source_model="chatgpt",
    )

    rows = _forecast_rows(theses)
    assert len(rows) == 1, rows
    assert rows[0]["target_session"] == FIXTURE_SESSION
    assert rows[0]["source_model"] == "chatgpt"
    # `target_week` is kept for the rows written before this packet; a DAILY
    # paste does not invent one.
    assert "target_week" in rows[0]


def test_nobody_typed_a_creation_time_so_none_is_claimed(journal):
    """Unchanged from WISHLIST 10K: `created_at_claimed` stays `unknown` rather
    than becoming the moment of the paste."""
    import market_thesis

    service, theses = journal
    service.import_daily_forecast(
        text=_fixture_text(), target_session=FIXTURE_SESSION, source_model="chatgpt"
    )
    assert _forecast_rows(theses)[0]["created_at_claimed"] == market_thesis.UNKNOWN


def test_a_second_paste_for_the_same_session_supersedes_the_first(journal):
    """Two pastes, one forecast on the page - and both rows still on disk."""
    import market_journal

    service, _theses = journal
    first = service.import_daily_forecast(
        text=_fixture_text(), target_session=FIXTURE_SESSION, source_model="chatgpt"
    )
    second = service.import_daily_forecast(
        text=_fixture_text() + "\n\nUpdate: the 10-year just took 5% back.",
        target_session=FIXTURE_SESSION,
        source_model="chatgpt",
    )

    assert first.get("ok") and second.get("ok")
    assert second["entry"]["supersedes"] == first["entry"]["entry_id"]

    # The ledger keeps both rows; the READ shows the newer one alone.
    current = service.entries_about(FIXTURE_SESSION)
    forecasts = [
        row
        for row in current
        if str(row.get("origin") or "") == market_journal.ORIGIN_EXTERNAL_FORECAST
    ]
    assert len(forecasts) == 1, forecasts
    assert forecasts[0]["entry_id"] == second["entry"]["entry_id"]
    assert "the 10-year just took 5% back" in forecasts[0]["text"]


def test_a_paste_for_a_different_session_supersedes_nothing(journal):
    service, _theses = journal
    first = service.import_daily_forecast(
        text=_fixture_text(), target_session=FIXTURE_SESSION, source_model="chatgpt"
    )
    other = service.import_daily_forecast(
        text="A different day's brief entirely.",
        target_session="2026-09-16",
        source_model="chatgpt",
    )
    assert other["entry"]["supersedes"] == ""
    assert other["entry"]["session_date"] == "2026-09-16"
    assert len(service.entries_about(FIXTURE_SESSION)) == 1
    assert service.entries_about(FIXTURE_SESSION)[0]["entry_id"] == first["entry"]["entry_id"]


def test_the_weekly_name_survives_one_release_as_a_deprecated_alias(journal):
    """`import_weekly_forecast` still writes: an old caller is not broken by a
    rename. It is MARKED deprecated so the next packet can delete it."""
    import market_journal

    service, _theses = journal
    result = service.import_weekly_forecast(
        text=_fixture_text(), source_model="chatgpt", session_date=FIXTURE_SESSION
    )
    assert result.get("ok"), result
    assert result["entry"]["origin"] == market_journal.ORIGIN_EXTERNAL_FORECAST
    doc = (type(service).import_weekly_forecast.__doc__ or "").lower()
    assert "deprecat" in doc, "the alias says it is on its way out"
