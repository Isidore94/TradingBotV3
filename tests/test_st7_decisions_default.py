def test_the_old_policies_by_name_reproduce_the_goldens_and_the_default_matches_the_new_pin():
    if os.environ.get(REGEN_ENV) == "1":  # pragma: no cover - tester/reviewer door
        _write_v2_record_golden(FIXTURES_DIR / f"{V2_RECORD_GOLDEN_NAME}.json")
        _write_v2_family_rows_golden(V2_FAMILY_ROWS_GOLDEN_CSV)

    policy = _sp()
    ec = _ec()

    # ---- (a) the ST3 replay golden, under the OLD convention BY NAME -------
    st3 = load_fixture_contract(ST3_GOLDEN_NAME)
    bars = st3["daily_bars"]
    st3_setup = st3["setup"]
    frame = _golden_frame(bars)

    old_record = m.recompute_tracker_setup_record(
        copy.deepcopy(st3_setup),
        frame,
        execution_convention=ec.EXECUTION_LITERAL_LEVEL_V1,
        level_knowledge=ec.LEVEL_KNOWLEDGE_SAME_SESSION_V1,
    )
    assert _canonical(_without_stamps(old_record)) == _canonical(_without_stamps(st3["record"]))
    # ...and the record NAMES the policy that produced it (ST7.1: the stamps
    # are no longer popped, so v1 is legible after the flip).
    assert old_record["execution_convention"] == ec.EXECUTION_LITERAL_LEVEL_V1
    assert old_record["level_knowledge"] == ec.LEVEL_KNOWLEDGE_SAME_SESSION_V1

    # ---- (b) the ST4 family-rows golden, under the OLD policy BY NAME ------
    st4_golden_text = ST4_GOLDEN_CSV.read_text(encoding="utf-8")
    st4_columns = next(csv.reader(io.StringIO(st4_golden_text)))
    old_rows = m.build_recent_tracker_setup_family_rows(
        _golden_setups(),
        reference_date=GOLDEN_REFERENCE_DATE,
        lookback_days=GOLDEN_LOOKBACK_DAYS,
        selection_policy=policy.SELECTION_CLOSED_FIRST_V1,
    )
    assert _rows_to_csv_text(old_rows, st4_columns) == st4_golden_text

    # ---- (c) the DEFAULT now reproduces the new v2 pins --------------------
    v2 = load_fixture_contract(V2_RECORD_GOLDEN_NAME)
    assert _canonical(v2["daily_bars"]) == _canonical(bars)
    assert _canonical(v2["setup"]) == _canonical(st3_setup)
    # The pin is worth having: it really differs from the v1 golden.
    assert _canonical(v2["record"]) != _canonical(_without_stamps(st3["record"]))

    default_record = m.recompute_tracker_setup_record(copy.deepcopy(st3_setup), frame)
    assert _canonical(_without_stamps(default_record)) == _canonical(v2["record"])
    assert default_record["execution_convention"] == ec.EXECUTION_GAP_AWARE_V2
    assert default_record["level_knowledge"] == ec.LEVEL_KNOWLEDGE_PRIOR_SESSION_V2

    v2_csv_text = V2_FAMILY_ROWS_GOLDEN_CSV.read_text(encoding="utf-8")
    v2_columns = next(csv.reader(io.StringIO(v2_csv_text)))
    assert v2_csv_text != st4_golden_text, "the new default really moves the rows"
    default_rows = m.build_recent_tracker_setup_family_rows(
        _golden_setups(),
        reference_date=GOLDEN_REFERENCE_DATE,
        lookback_days=GOLDEN_LOOKBACK_DAYS,
    )
    assert _rows_to_csv_text(default_rows, v2_columns) == v2_csv_text

    # ---- (d) no residue: the old arm is still the old arm afterwards -------
    again = m.recompute_tracker_setup_record(
        copy.deepcopy(st3_setup),
        frame,
        execution_convention=ec.EXECUTION_LITERAL_LEVEL_V1,
        level_knowledge=ec.LEVEL_KNOWLEDGE_SAME_SESSION_V1,
    )
    assert _canonical(_without_stamps(again)) == _canonical(_without_stamps(st3["record"]))


