def test_every_record_and_family_row_carries_its_policy_stamps_under_the_default():
    ec = _ec()
    policy = _sp()

    bars = _build_golden_daily_bars()
    setup = _build_golden_setup(bars)
    frame = _golden_frame(bars)

    # A DEFAULT replay no longer pops the two execution stamps.
    default_record = m.recompute_tracker_setup_record(copy.deepcopy(setup), frame)
    assert default_record["execution_convention"] == ec.EXECUTION_GAP_AWARE_V2
    assert default_record["level_knowledge"] == ec.LEVEL_KNOWLEDGE_PRIOR_SESSION_V2

    # ...and neither does an explicit OLD-policy replay: after the flip a
    # record with no stamp is ambiguous, so v1 has to say so too.
    old_record = m.recompute_tracker_setup_record(
        copy.deepcopy(setup),
        frame,
        execution_convention=ec.EXECUTION_LITERAL_LEVEL_V1,
        level_knowledge=ec.LEVEL_KNOWLEDGE_SAME_SESSION_V1,
    )
    assert old_record["execution_convention"] == ec.EXECUTION_LITERAL_LEVEL_V1
    assert old_record["level_knowledge"] == ec.LEVEL_KNOWLEDGE_SAME_SESSION_V1

    # Every family row carries the selection policy under the default.
    rows = m.build_recent_tracker_setup_family_rows(
        _pending_and_reentry_population(),
        reference_date=date(2026, 1, 20),
        lookback_days=45,
    )
    assert rows
    for row in rows:
        assert row["selection_policy"] == policy.SELECTION_FIRST_ACTIONABLE_V2

    # And the summary the scoring projection freezes into the snapshot says it
    # too - that projection is the ONLY copy of the answer for the live
    # scoring path, so an unstamped one cannot be told apart from an old one.
    summary = m._summarize_tracker_setup_outcome(
        _pending_and_reentry_population()["pending"]
    )
    assert summary["selection_policy"] == policy.SELECTION_FIRST_ACTIONABLE_V2
    assert summary["representative_status"] == "pending"

    scoring_payload = m.build_setup_tracker_scoring_payload(
        {"setups": _pending_and_reentry_population()}
    )
    projected = scoring_payload["setups"]["pending"]["_scoring_outcome_summary"]
    assert projected["selection_policy"] == policy.SELECTION_FIRST_ACTIONABLE_V2
    assert projected["representative_status"] == "pending"


