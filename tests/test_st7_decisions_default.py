PENDING_FAMILY = "avwape_bounce"
REENTRY_FAMILY = "post_earnings_52w_break"


def _pending_and_reentry_population() -> dict[str, dict]:
    """One thesis still running, one thesis entered twice.

    The pending thesis is the ST4 shape that made this decision necessary: the
    representative exit plan (`full_band2` on the primary stop) is still OPEN
    while an ALTERNATE plan on the same stop closed at -1.00R. Today the family
    row reports that -1.00R as the trade's result, so a position still on the
    books is counted as a realized loss.
    """
    pending = _st4_setup(
        symbol="NVDA", side="LONG", anchor_date="2026-01-02", scan_date="2026-01-05",
        setup_family=PENDING_FAMILY, setup_status="OPEN",
        scenarios=[
            _st4_scenario(scenario_id="a", stop_label="LOWER_1", exit_template_id="full_band2",
                          status="OPEN", total_r=0.4),
            _st4_scenario(scenario_id="b", stop_label="LOWER_1", exit_template_id="full_band3",
                          status="STOPPED", total_r=-1.0, exit_date="2026-01-13"),
        ],
    )
    first_attempt = _st4_setup(
        symbol="AMD", side="LONG", anchor_date="2026-01-02", scan_date="2026-01-05",
        setup_family=REENTRY_FAMILY, setup_status="CLOSED",
        scenarios=[
            _st4_scenario(scenario_id="c", stop_label="LOWER_1", exit_template_id="full_band2",
                          status="TARGET_HIT", total_r=2.0, exit_date="2026-01-09"),
        ],
    )
    # The first attempt was OUT on 01-09; this is a declared re-entry, not the
    # rescan of a live position.
    second_attempt = _st4_setup(
        symbol="AMD", side="LONG", anchor_date="2026-01-02", scan_date="2026-01-13",
        setup_family=REENTRY_FAMILY, setup_status="CLOSED",
        scenarios=[
            _st4_scenario(scenario_id="d", stop_label="LOWER_1", exit_template_id="full_band2",
                          status="TARGET_HIT", total_r=1.0, exit_date="2026-01-16"),
        ],
    )
    return {
        "pending": pending,
        "attempt_1": first_attempt,
        "attempt_2": second_attempt,
    }


def _row_for(rows, family):
    return next(row for row in rows if str(row.get("setup_family")) == family)


def test_a_default_family_build_leaves_a_pending_representative_ungraded_and_counts_the_reentry():
    population = _pending_and_reentry_population()

    # THE DEFAULT CALL - no policy keyword anywhere.
    rows = m.build_recent_tracker_setup_family_rows(
        population, reference_date=date(2026, 1, 20), lookback_days=45
    )

    pending_row = _row_for(rows, PENDING_FAMILY)
    assert int(pending_row["n_pending"] or 0) == 1
    assert int(pending_row["n_losses"] or 0) == 0, "a trade still on is not a loss"
    assert int(pending_row["n_wins"] or 0) == 0
    assert int(pending_row["n_flats"] or 0) == 0
    assert int(pending_row["closed_setups"] or 0) == 0
    assert pending_row["representative_closed_r"] is None
    assert pending_row["win_rate_closed_unweighted"] is None
    assert str(pending_row["selection_policy"]) == _sp().SELECTION_FIRST_ACTIONABLE_V2

    reentry_row = _row_for(rows, REENTRY_FAMILY)
    assert int(reentry_row["n_episodes"] or 0) == 2, "a second entry after a close is its own trade"
    assert int(reentry_row["n_observations"] or 0) == 2
    assert int(reentry_row["n_wins"] or 0) == 2
    assert int(reentry_row["n_losses"] or 0) == 0
    assert int(reentry_row["n_entry_sessions"] or 0) == 2

    # The old policy, BY NAME, still answers the way the desk answered
    # yesterday - the characterization the decision was taken against.
    old = m.build_recent_tracker_setup_family_rows(
        population,
        reference_date=date(2026, 1, 20),
        lookback_days=45,
        selection_policy=_sp().SELECTION_CLOSED_FIRST_V1,
    )
    old_pending = _row_for(old, PENDING_FAMILY)
    assert int(old_pending["n_losses"] or 0) == 1
    assert int(old_pending["n_pending"] or 0) == 0
    assert old_pending["representative_closed_r"] == pytest.approx(-1.0)
    old_reentry = _row_for(old, REENTRY_FAMILY)
    assert int(old_reentry["n_episodes"] or 0) == 1
    assert int(old_reentry["n_observations"] or 0) == 2


