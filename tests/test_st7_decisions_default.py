def test_the_tracker_defaults_are_the_repaired_policies_and_v1_keeps_its_name():
    policy = _sp()
    ec = _ec()

    assert policy.DEFAULT_SELECTION_POLICY == policy.SELECTION_FIRST_ACTIONABLE_V2
    assert ec.DEFAULT_EXECUTION_CONVENTION == ec.EXECUTION_GAP_AWARE_V2
    assert ec.DEFAULT_LEVEL_KNOWLEDGE == ec.LEVEL_KNOWLEDGE_PRIOR_SESSION_V2

    # The values themselves never move - a stamp written last month must still
    # mean what it meant.
    assert policy.SELECTION_CLOSED_FIRST_V1 == "closed_first_v1"
    assert policy.SELECTION_FIRST_ACTIONABLE_V2 == "first_actionable_v2"
    assert ec.EXECUTION_LITERAL_LEVEL_V1 == "literal_level_v1"
    assert ec.EXECUTION_GAP_AWARE_V2 == "gap_aware_v2"
    assert ec.LEVEL_KNOWLEDGE_SAME_SESSION_V1 == "same_session_v1"
    assert ec.LEVEL_KNOWLEDGE_PRIOR_SESSION_V2 == "prior_session_v2"

    # The old arm the comparison CLIs call "old" is still selectable by name.
    assert policy.resolve_policy(policy.SELECTION_CLOSED_FIRST_V1) == "closed_first_v1"
    assert ec.is_gap_aware(ec.EXECUTION_LITERAL_LEVEL_V1) is False
    assert ec.is_gap_aware(ec.EXECUTION_GAP_AWARE_V2) is True
