# 3 (ST7.1) - the default replay books reachable prices off known levels.
# ---------------------------------------------------------------------------
def test_a_default_replay_books_the_gap_open_and_refuses_a_same_session_band():
    ec = _ec()

    # (a) the review fixture, through the bar evaluator's SHIPPED signature:
    # entry 100, risk 5, hard stop 95, next bar O80/H85/L79/C82. The bar never
    # traded at 95; -4.014R is derived from the shipped cost constants.
    gap_bar = _bar(open_=80, high=85, low=79, close=82)
    scenario = _st3_scenario(hard_stop_r_multiple=1.0)
    events = m._evaluate_tracker_scenario_bar(
        scenario, "LONG", "2026-01-05", gap_bar, None, None, is_entry_day=False, bar_index=2
    )
    assert _reasons(events) == ["HARD_STOP"]
    assert events[0]["price"] == pytest.approx(80.0)
    assert events[0]["fill_basis"] == ec.FILL_BASIS_GAP_OPEN
    assert events[0]["execution_convention"] == ec.EXECUTION_GAP_AWARE_V2
    assert scenario["realized_r"] == pytest.approx(_expected_r(100.0, 80.0, 100, 1.0, 500.0))
    assert scenario["realized_r"] == pytest.approx(-4.014)

    # (b) the same repair through the whole record replay, on the ST3 golden
    # setup whose bar 32 gaps clean through the stop.
    bars = _build_golden_daily_bars()
    setup = _build_golden_setup(bars)
    record = m.recompute_tracker_setup_record(copy.deepcopy(setup), _golden_frame(bars))
    booked = record["scenarios"]["full_band3"]["events"]
    stops = [event for event in booked if event["reason"] == "HARD_STOP"]
    assert stops, "the gap bar still stops the scenario out"
    gap_open = float(bars[GOLDEN_GAP_IDX]["open"])
    assert stops[0]["price"] == pytest.approx(gap_open)
    assert stops[0]["fill_basis"] == ec.FILL_BASIS_GAP_OPEN

    # (c) the same-session band: day D's UPPER_3 is inside D's own range only
    # because D's own bar was folded into the cumulative sums. The default no
    # longer books that target.
    df, anchor, prev_key = _band_moves_inside_its_own_bar_frame()
    day_key = df.iloc[-1]["datetime"].date().isoformat()
    history = m.calc_anchored_vwap_band_history(df, anchor)
    assert (
        float(history[day_key]["bands"]["UPPER_3"])
        < float(df.iloc[-1]["high"])
        < float(history[prev_key]["bands"]["UPPER_3"])
    ), "the fixture's premise: today's band is reachable, yesterday's is not"

    band_setup = _band_move_setup(df, anchor, prev_key)
    replayed = m.recompute_tracker_setup_record(copy.deepcopy(band_setup), df)
    repaired = replayed["scenarios"]["s1"]
    assert _reasons(repaired["events"]) == []
    assert m._scenario_is_open(repaired["status"])

    # The old convention, BY NAME, still books both - the arm the comparison
    # CLIs call "old" is reproducible forever.
    old_band = m.recompute_tracker_setup_record(
        copy.deepcopy(band_setup),
        df,
        level_knowledge=ec.LEVEL_KNOWLEDGE_SAME_SESSION_V1,
    )
    assert _reasons(old_band["scenarios"]["s1"]["events"]) == ["FINAL_TARGET"]
    old_scenario = _st3_scenario(hard_stop_r_multiple=1.0)
    old_events = m._evaluate_tracker_scenario_bar(
        old_scenario, "LONG", "2026-01-05", _bar(open_=80, high=85, low=79, close=82),
        None, None, is_entry_day=False, bar_index=2,
        execution_convention=ec.EXECUTION_LITERAL_LEVEL_V1,
    )
    assert old_events[0]["price"] == pytest.approx(95.0)
    assert old_scenario["realized_r"] == pytest.approx(-1.014)


