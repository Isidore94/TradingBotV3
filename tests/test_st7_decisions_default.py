    assert ec.uses_prior_session_levels(ec.LEVEL_KNOWLEDGE_PRIOR_SESSION_V2) is True

    # ...and an EMPTY policy still resolves to the default rather than raising,
    # so an old row whose stamp is present and empty reads as the default.
    assert policy.resolve_policy("") == policy.SELECTION_FIRST_ACTIONABLE_V2

    # The compatibility entrypoint every caller actually imports moved too.
    assert m.DEFAULT_EXECUTION_CONVENTION == ec.EXECUTION_GAP_AWARE_V2
    assert m.DEFAULT_LEVEL_KNOWLEDGE == ec.LEVEL_KNOWLEDGE_PRIOR_SESSION_V2


