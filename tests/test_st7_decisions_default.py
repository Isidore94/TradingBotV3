# 6 (ST7.1) - the ST4 cache rule survives the flip.
# ---------------------------------------------------------------------------
def _old_compact_projection(stamp_shape: str) -> dict:
    """A record as `master_avwap_tracker_scoring_snapshot.json` holds it.

    No `scenarios` key AT ALL - the projection is compact - and a summary
    written BEFORE ST4 existed, so its policy stamp is either absent (the
    column did not exist) or present and empty (a row half-migrated). Both
    shapes are on disk somewhere; neither may cause a recompute, because the
    recompute finds no scenarios and drops the setup (32 recent family rows ->
    0, measured 2026-09-06).
    """
    source = _st4_setup(
        symbol="NVDA", side="LONG", anchor_date="2026-01-02", scan_date="2026-01-05",
        setup_family=PENDING_FAMILY, setup_status="CLOSED",
        scenarios=[
            _st4_scenario(scenario_id="a", stop_label="LOWER_1", exit_template_id="full_band2",
                          status="TARGET_HIT", total_r=2.0, exit_date="2026-01-09"),
        ],
    )
    projection = m._tracker_scoring_setup_projection(source)
    assert "scenarios" not in projection
    summary = projection["_scoring_outcome_summary"]
    for key in ("selection_policy", "as_of_session"):
        if stamp_shape == "absent":
            summary.pop(key, None)
        else:
            summary[key] = ""
    return projection


@pytest.mark.parametrize("stamp_shape", ["absent", "present_and_empty"])
def test_a_compact_projection_without_a_policy_stamp_is_still_read_as_is(stamp_shape):
    policy = _sp()
    projection = _old_compact_projection(stamp_shape)
    cached = copy.deepcopy(projection["_scoring_outcome_summary"])

    # The default read takes the cache UNCONDITIONALLY - the ST4 rule, now
    # exercised under the NEW default, which is the policy that used to take
    # the `unknown_compact` bypass.
    default_summary = m._summarize_tracker_setup_outcome(projection)
    assert default_summary == cached
    assert default_summary.get("representative_status") != "unknown_compact"

    # Naming the new default explicitly is the same read.
    named = m._summarize_tracker_setup_outcome(
        projection, policy=policy.SELECTION_FIRST_ACTIONABLE_V2
    )
    assert named == cached

    # And the population does not collapse: the family build still counts it.
    rows = m.build_recent_tracker_setup_family_rows(
        {"compact": copy.deepcopy(projection)},
        reference_date=date(2026, 1, 20),
        lookback_days=45,
    )
    assert len(rows) == 1
    row = rows[0]
    assert int(row["n_episodes"] or 0) == 1
    assert "unknown_compact" not in str(row["excluded_reasons"])
    assert int(row["n_excluded"] or 0) == 0

    # The bypass itself is NOT removed - it is what a read that cannot be
    # answered from the cache still says. An `as_of` replay of a compact
    # record has to look at scenarios that are not there, and names that
    # rather than grading a trade it could not have seen.
    replayed = m._summarize_tracker_setup_outcome(projection, as_of_session="2026-01-07")
    assert replayed["representative_status"] == "unknown_compact"
