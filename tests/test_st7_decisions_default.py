"""Packet ST7 - the trader's three decisions become the tracker's defaults.

Written RED, on `main` at 68762909, before any of the flips exist.

ST3 and ST4 built `gap_aware_v2` / `prior_session_v2` / `first_actionable_v2`
as OPT-IN evidence with the shipped policy still the default. The trader took
the three decisions on 2026-09-06 (~21:15 PT): *"Yes a trade not yet completed
should say pending. A second entry after a first close is its own trade yes.
3. This one is up to your discretion."* - and the lead's discretion on (3) made
both execution repairs the default. ST7 is that flip and nothing wider.

What this file pins, item by item (ST7.1 / ST7.2):

1. ``selection_policy.DEFAULT_SELECTION_POLICY`` is ``first_actionable_v2``;
   ``execution_convention.DEFAULT_EXECUTION_CONVENTION`` is ``gap_aware_v2``
   and ``DEFAULT_LEVEL_KNOWLEDGE`` is ``prior_session_v2``. The v1 names keep
   their values and stay selectable.
2. A DEFAULT `build_recent_tracker_setup_family_rows` leaves a pending
   representative in ``n_pending`` and never grades it from `avg_closed_r`,
   and a re-entry after a closed attempt is its own episode.
3. A DEFAULT `recompute_tracker_setup_record` / `_evaluate_tracker_scenario_bar`
   books the gap OPEN, and does not book a target off a band that only its own
   close could have known.
4. The old policies CALLED BY NAME still reproduce the ST3 and ST4 goldens,
   and the default reproduces the new v2 goldens pinned here from `main`.
5. Every record carries ``execution_convention`` / ``level_knowledge`` and
   every family row carries ``selection_policy`` under the default - a default
   run no longer POPS the stamps (`legacy.py` `:7301-7308`), because a record
   that does not say which policy produced it is unreadable after a flip.
6. The ST4 cache rule survives the flip: a compact scoring projection written
   under the OLD default carries no policy stamp and is still read AS-IS, so
   the live scoring population does not collapse to zero.

**Nothing here is generated by the code under test.** The two new goldens
(`st7_v2_default_golden.json`, `st7_family_rows_v2_default_golden.csv`) were
pinned on `main` through the EXPLICIT v2 keyword arguments that already ship -
the same numbers the flip must produce by default - not from a branch that had
already flipped. `ST7_REGEN_GOLDEN=1` re-pins them; the door exists for the
tester and the reviewer and no build may use it.

The ST3 and ST4 fixture builders are IMPORTED rather than copied: a fixture
this file re-typed could drift away from the one the goldens were pinned on,
and then "the old policy still reproduces the golden" would prove nothing.
"""

