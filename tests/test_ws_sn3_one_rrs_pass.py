def _session_bar_times(session_date, count=BARS_PER_SESSION):
    start = datetime(
        session_date.year,
        session_date.month,
        session_date.day,
        SESSION_OPEN_HOUR,
        SESSION_OPEN_MINUTE,
    )
    return [start + timedelta(minutes=5 * i) for i in range(count)]


def _build_series(symbol, *, sessions=SESSION_DATES, extra_bars=0):
    """A deterministic OHLC walk that respects low <= open, close <= high."""
    seed, price, drift = SERIES_RECIPE[symbol]
    rng = random.Random(seed)
    times = []
    for session_date in sessions:
        times.extend(_session_bar_times(session_date))
    if extra_bars:
        last = times[-1]
        times.extend(last + timedelta(minutes=5 * (i + 1)) for i in range(extra_bars))
    bars = []
    for index, dt in enumerate(times):
        open_ = price
        step = drift + rng.uniform(-0.35, 0.35) * (open_ * 0.002)
        close = round(open_ + step, 4)
        span = abs(open_ * 0.0012) + abs(step) * 0.6 + 0.01
        high = round(max(open_, close) + rng.uniform(0.05, 1.0) * span, 4)
        low = round(min(open_, close) - rng.uniform(0.05, 1.0) * span, 4)
        bars.append(
            bounce_bot.IbBar(
                dt=dt,
                open=round(open_, 4),
                high=high,
                low=low,
                close=close,
                volume=float(10_000 + index),
            )
        )
        price = close
    return bars


def _recorded_universe(extra_bars_for=None):
    """symbol -> bars.  ``extra_bars_for`` grows only the named symbols."""
    extra = dict(extra_bars_for or {})
