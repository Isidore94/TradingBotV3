def _run_three_cycles(monkeypatch):
    """Cycle 1: SPY and every name end at T.  Cycle 2: SPY and AMD gain one
    bar (AMD's last dt MOVES, WFC's does not).  Cycle 3: nothing moves.

    The payloads collected are the 5m ones: one extra 5-minute bar only opens
    a PARTIAL 15m/1h bucket, which ``_aggregate_bars_timeframe`` drops, so 5m
    is the timeframe where a moved last bar is visible in the output.
    """
    bot = _make_bot(_recorded_universe(), monkeypatch=monkeypatch)
    counter = ProfileCounter(bot)
    payloads = []

    grown = {SPY_SYMBOL: 1, "AMD": 1}
    for cycle_index in range(3):
        if cycle_index == 1:
            set_universe(bot, _recorded_universe(extra_bars_for=grown))
        counter.start_cycle()
        bot.run_rrs_scan()
        payloads.append(bot.rrs_payload_for("5m"))
    return bot, counter, payloads


def test_a_moved_last_bar_dt_invalidates_the_profile_cache(monkeypatch):
    """AMD gains a bar in cycle 2: rebuilt once there, reused in cycle 3."""
    bot, counter, payloads = _run_three_cycles(monkeypatch)

    assert counter.counts("AMD") == (1, 1, 0)
    # The new bar reached the output, so this is a real rebuild and not a
    # stale cache handed back under a new key.
    assert payloads[1]["rrs_all"]["AMD"] != payloads[0]["rrs_all"]["AMD"]
    assert payloads[2]["rrs_all"]["AMD"] == payloads[1]["rrs_all"]["AMD"]


def test_a_symbol_with_no_new_bar_is_not_reprofiled(monkeypatch):
    """WFC never gains a bar, so it is profiled once across three cycles."""
    bot, counter, payloads = _run_three_cycles(monkeypatch)

    assert counter.counts("WFC") == (1, 0, 0)
    assert payloads[1]["rrs_all"]["WFC"] == payloads[0]["rrs_all"]["WFC"]
