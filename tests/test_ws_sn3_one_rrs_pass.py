class ProfileCounter:
    """Counts real ``_build_intraday_rrs_profile`` calls per symbol per cycle."""

    def __init__(self, bot):
        self._real = bot._build_intraday_rrs_profile
        self._bot = bot
        self.cycles = []
        self._current = None
        bot._build_intraday_rrs_profile = self

    def __call__(self, symbol_bars, spy_bars, length=bounce_bot.IMPULSE_RRS_PROFILE_LENGTH):
        if self._current is not None and symbol_bars:
            key = self._symbol_for(symbol_bars)
            self._current[key] = self._current.get(key, 0) + 1
        return self._real(symbol_bars, spy_bars, length=length)

    def _symbol_for(self, symbol_bars):
        for key, bars in self._bot.latest_bars.items():
            if "|" in key:
                continue
            if bars is symbol_bars:
                return key
        return "?"

    def start_cycle(self):
        self._current = {}
        self.cycles.append(self._current)

    def counts(self, symbol):
        return tuple(cycle.get(symbol, 0) for cycle in self.cycles)


# --- canonical serialization ---------------------------------------------


def _json_default(value):
    if isinstance(value, datetime):
        return {"__datetime__": value.isoformat()}
    if isinstance(value, date):
        return {"__date__": value.isoformat()}
    if isinstance(value, (set, frozenset)):
        return sorted(value)
    raise TypeError("not serializable: %r" % (type(value),))


def canonical(payload):
    """The byte-for-byte form.  ``timestamp`` is wall-clock and is excluded."""
    body = {key: value for key, value in dict(payload).items() if key != "timestamp"}
    return json.dumps(body, sort_keys=True, separators=(",", ":"), default=_json_default)


def canonical_extremes(extremes):
    return json.dumps(extremes, sort_keys=True, separators=(",", ":"), default=_json_default)


