def _record_four_passes(monkeypatch):
    """Run the four passes exactly as ``run_strategy`` does today."""
    bot = _make_bot(_recorded_universe(), monkeypatch=monkeypatch)
    passes = {}
    for timeframe_key in CYCLE_TIMEFRAMES:
        bot.run_rrs_scan(timeframe_key_override=timeframe_key, emit_gui=False)
        passes[timeframe_key] = canonical(bot.latest_rrs_payload)
    bot.run_rrs_scan()
    passes["gui"] = canonical(bot.latest_rrs_payload)
    return {
        "passes": passes,
        "scan_extremes": canonical_extremes(bot.latest_scan_extremes),
        "gui_timeframe_key": GUI_TIMEFRAME_KEY,
    }


