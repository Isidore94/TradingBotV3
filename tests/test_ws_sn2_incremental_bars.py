class Harness:
    """A real ``BounceBot`` whose fetch path is real and whose IB is fake.

    Real: ``request_and_detect_bounce``, ``historicalData``,
    ``historicalDataEnd``, ``_bars_to_ib``, ``_dedupe_bars``, the DataFrame
    build and ``_prune_latest_bars_for_cycle``.  Stubbed: the socket, the
    evidence emitters, and the Focus/watchlist file readers.
    """

    def __init__(self, monkeypatch, series=None, symbol=SYMBOL):
        bot = object.__new__(bounce_bot.BounceBot)
        bot.data_lock = threading.Lock()
        bot.data = {}
        bot.data_ready_events = {}
        bot.latest_bars = {}
        bot.symbol_metrics = {}
        bot.pending_bounce_outcomes = {}
        bot.longs = [SYMBOL, OTHER_SYMBOL]
        bot.shorts = []
        bot.auto_longs = []
        bot.auto_shorts = []
        bot.master_avwap_d1_watchlist = {}
        bot.master_avwap_focus_map = {}

        self.bot = bot
        self.frames = []  # every frame the detectors were handed, in order
        self.series_by_symbol = {}
        base = recorded_series(symbol) if series is None else list(series)
        self.series_by_symbol[symbol] = base
        self.ib = FakeIb(bot, base)

        bot.reqHistoricalData = self._req
        bot.create_stock_contract = lambda sym: SimpleNamespace(symbol=sym)
        bot.getReqId = self.ib.get_req_id

        # Capture point: the full frame every downstream reader is built from.
        def _capture(sym, df):
            self.frames.append((self.ib.cycle_index, sym, df))

        bot._update_pending_bounce_outcomes = _capture
        bot.emit_master_avwap_intraday_trigger_flags = lambda *a, **k: None
        bot.emit_master_avwap_zone_arm_flags = lambda *a, **k: None
        bot.emit_master_avwap_tier_flip_flags = lambda *a, **k: None
        bot._human_focus_side_for_symbol = lambda sym: ""
        bot._auto_watch_symbols = lambda side: set()

        market_tz, _name = get_market_local_timezone()
        self._market_tz = market_tz
        monkeypatch.setattr(
            bounce_bot,
            "get_market_local_now",
            lambda *args, **kwargs: self.ib.now.replace(tzinfo=market_tz),
        )

    def add_symbol(self, symbol):
        self.series_by_symbol[symbol] = recorded_series(symbol)

    def _req(self, **kwargs):
        symbol = getattr(kwargs.get("contract"), "symbol", None)
        self.ib.series = self.series_by_symbol[symbol]
        self.ib.req_historical_data(**kwargs)

    # -- driving ----------------------------------------------------------

    def cycle(self, now, symbols=(SYMBOL,)):
        """One scan cycle: the clock moves, then each symbol is scanned once."""
        self.ib.start_cycle(now)
        for symbol in symbols:
            self.bot.request_and_detect_bounce(symbol, scan_for_new_bounces=False)
        return self.ib.cycle_index

    def frame_for(self, symbol, cycle_index):
        """The frame handed to the detectors for ``symbol`` in THAT cycle.

        A cycle that built no frame is a failure, not an empty result: the
        ten-bar short-data guard swallowing a five-bar delta would otherwise
        read as "nothing to compare".
        """
        matches = [
            df for cycle, sym, df in self.frames if sym == symbol and cycle == cycle_index
        ]
        assert matches, (
            "cycle %s built no frame for %s at all - the detectors were handed "
            "nothing that cycle (requests: %s)"
            % (
                cycle_index,
                symbol,
                [
                    (req.duration, req.served)
                    for req in self.ib.requests_in_cycle(cycle_index)
                    if req.symbol == symbol
                ],
            )
        )
        assert len(matches) == 1, (
            "cycle %s built %s frames for %s; one scan is one frame"
            % (cycle_index, len(matches), symbol)
        )
        return matches[0]


def fresh_full_fetch_frame(monkeypatch, now, series=None):
    """What one fresh ``5 D`` fetch produces at ``now`` - the golden reference."""
    harness = Harness(monkeypatch, series=series)
    harness.cycle(now)
    frame = harness.frame_for(SYMBOL, 0)
    only = harness.ib.requests
    assert len(only) == 1 and only[0].duration == FULL_WINDOW_DURATION, (
        "the reference fetch must be one whole-window request, got %s"
        % ([req.duration for req in only],)
    )
    return frame


# --------------------------------------------------- the golden fixture I/O


def frame_to_record(frame):
    """Columns, dtypes and rows - so the reader rebuilds the frame EXACTLY,
    dtypes included.  A fixture that loses ``volume``'s int64 cannot catch a
    merge that turned it into a float."""
    columns = list(frame.columns)
    rows = []
    for row in frame.itertuples(index=False, name=None):
        rows.append(
            [
                value.isoformat() if isinstance(value, pd.Timestamp) else value
                for value in row
            ]
        )
    return {
        "columns": columns,
        "dtypes": {name: str(dtype) for name, dtype in frame.dtypes.items()},
        "rows": rows,
    }


def record_to_frame(record):
    frame = pd.DataFrame(record["rows"], columns=record["columns"])
    return frame.astype(record["dtypes"])


