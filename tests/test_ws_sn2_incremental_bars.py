"""WS-SN2 - fetch new M5 bars only (WISHLIST item 4, required result 2).

Written BEFORE the fix; every test here must FAIL on the pre-SN2 code.

Today ``BounceBot.request_and_detect_bounce``
(``scripts/bounce_bot_lib/legacy.py``) asks IB for ``durationStr="5 D"`` of
5-minute bars for EVERY symbol on EVERY cycle - ~390 bars / ~206 KB a symbol,
586 symbol scans a cycle, ~120 MB fetched and ~230,000 rows parsed every 25
minutes, all on the interpreter lock the GUI needs (trader, 2026-09-08).

SN2 fetches the five days ONCE per symbol per day, keeps the frame, and then
asks only for the bars since the last COMPLETED one.  The thing that must not
change is the frame: **what the detectors read after a delta fetch is
byte-for-byte what a fresh full fetch would have produced**, dtypes and index
included.  That is what the golden fixture pins.

The three faults these tests exist for:

* a FORMING bar that slipped into the cache must force a whole-window refetch,
  never a merge (a merged forming bar is a detector reading a preview as a
  state transition - ``plan.md`` sec 5);
* a delta that does not line up with the cache (the overlap bar's dt or close
  moved - a revision, a corporate action, a halt) must force a whole-window
  refetch;
* a symbol that leaves the scanned set must not keep its frame in memory.

The seam the builder is expected to add (used by the last test):
``BounceBot.cached_bounce_frame(symbol)`` returns whatever the SN2 cache is
holding for that symbol - any shape the builder likes - or ``None`` when
nothing is retained.  These tests only ever ask whether it is ``None``.

Nothing here touches a live store or a socket: the bars are a recorded
synthetic series and IB is a fake that answers ``reqHistoricalData`` the way
TWS does (honouring ``durationStr`` and ``endDateTime``, completed bars only
unless the test asks for a forming one).

Trap the builder should know about before reading the failures: the existing
``if len(all_bars) < 10: return`` guard is about the WHOLE window.  A realistic
delta is five bars (one 25-minute cycle), so that guard must move to the merged
result or the delta path returns early and builds no frame at all.
"""

