# --------------------------------------------------------- the recorded bars


def _session_bar_starts(session_date, count=BARS_PER_SESSION):
    start = datetime(
        session_date.year,
        session_date.month,
        session_date.day,
        SESSION_OPEN_HOUR,
        SESSION_OPEN_MINUTE,
    )
    return [start + timedelta(minutes=BAR_MINUTES * i) for i in range(count)]


def recorded_series(symbol=SYMBOL):
    """A deterministic OHLCV walk honouring ``low <= open, close <= high``.

    Rows are the raw dicts ``historicalData`` appends, so what the fake serves
    is exactly what the real callback would have.
    """
    seed, price, drift = SERIES_RECIPE[symbol]
    rng = random.Random(seed)
    starts = []
    for session_date in SESSION_DATES:
        starts.extend(_session_bar_starts(session_date))
    rows = []
    for index, bar_start in enumerate(starts):
        open_ = price
        step = drift + rng.uniform(-0.35, 0.35) * (open_ * 0.002)
        close = round(open_ + step, 4)
        span = abs(open_ * 0.0012) + abs(step) * 0.6 + 0.01
        high = round(max(open_, close) + rng.uniform(0.05, 1.0) * span, 4)
        low = round(min(open_, close) - rng.uniform(0.05, 1.0) * span, 4)
        rows.append(
            {
                "start": bar_start,
                "time": bar_start.strftime(IB_TIME_FORMAT),
                "open": round(open_, 4),
                "high": high,
                "low": low,
                "close": close,
                "volume": 10_000 + index,
            }
        )
        price = close
    return rows


def revise_close_of_bar_starting(rows, bar_start, new_close):
    """A revised print on an already-served bar - the fault the identity check
    exists for.  Returns a new series; the original is untouched."""
    revised = []
    found = False
    for row in rows:
        if row["start"] == bar_start:
            row = dict(row)
            row["close"] = new_close
            row["high"] = max(row["high"], new_close)
            row["low"] = min(row["low"], new_close)
            found = True
        revised.append(row)
    assert found, "no bar starts at %s; the revision test proves nothing" % (bar_start,)
    return revised


# ------------------------------------------------------------------ fake IB


def duration_seconds(duration_text):
    """IB duration string -> seconds.  Unknown units fail loudly."""
    parts = str(duration_text or "").strip().split()
    if len(parts) != 2:
        raise AssertionError("unreadable durationStr %r" % (duration_text,))
    size = int(parts[0])
    unit = parts[1].upper()
    if unit == "S":
        return size
    if unit == "D":
        return size * 86_400
    if unit == "W":
        return size * 7 * 86_400
    raise AssertionError(
        "durationStr %r uses a unit this fake does not serve; SN2 should ask "
        "in seconds or days" % (duration_text,)
    )


def is_whole_window_request(request):
    """A request for the full five days, however it is spelled."""
    return duration_seconds(request.duration) >= 86_400


class FakeIb:
    """Answers ``reqHistoricalData`` from a recorded series, the way TWS does.

    * ``endDateTime=""`` means "up to now"; an explicit stamp is honoured.
    * ``durationStr`` in days selects that many SESSIONS ending at the end
      stamp (this is what makes "5 D" slide across a day roll and drop the
      oldest session); a duration in seconds selects a wall-clock window.
    * Only COMPLETED bars are served (``bar_start + 5 min <= end``) unless
      ``serve_forming_bar`` is on - that switch is how the partial-last-bar
      fault is injected.
    """

    def __init__(self, bot, series):
        self.bot = bot
        self.series = list(series)
        self.now = CYCLE_1_NOW
        self.serve_forming_bar = False
        self.requests = []  # every request, in order
        self.cycle_index = -1
        self._next_req_id = 1000

    # -- harness ----------------------------------------------------------

    def start_cycle(self, now):
        self.cycle_index += 1
        self.now = now

    def requests_in_cycle(self, cycle_index):
        return [req for req in self.requests if req.cycle == cycle_index]

    def bars_served_in_cycle(self, cycle_index):
        return sum(req.served for req in self.requests_in_cycle(cycle_index))

    # -- the IB seam ------------------------------------------------------

    def get_req_id(self):
        self._next_req_id += 1
        return self._next_req_id

    def req_historical_data(self, **kwargs):
        req_id = kwargs["reqId"]
        end_text = str(kwargs.get("endDateTime") or "").strip()
        end = self.now if not end_text else _parse_end_stamp(end_text)
        duration = kwargs.get("durationStr")
        record = SimpleNamespace(
            cycle=self.cycle_index,
            symbol=getattr(kwargs.get("contract"), "symbol", None),
            duration=duration,
            bar_size=kwargs.get("barSizeSetting"),
            end=end_text,
            served=0,
        )
        self.requests.append(record)

        for row in self._rows_for(duration, end):
            record.served += 1
            self.bot.historicalData(
                req_id,
                SimpleNamespace(
                    date=row["time"],
                    open=row["open"],
                    high=row["high"],
                    low=row["low"],
                    close=row["close"],
                    volume=row["volume"],
                ),
            )
        self.bot.historicalDataEnd(req_id, "", "")

    def _rows_for(self, duration, end):
        span = timedelta(minutes=BAR_MINUTES)
        if self.serve_forming_bar:
            visible = [row for row in self.series if row["start"] <= end]
        else:
            visible = [row for row in self.series if row["start"] + span <= end]
        if not visible:
            return []
        seconds = duration_seconds(duration)
        if seconds >= 86_400:
            sessions = sorted({row["start"].date() for row in visible})
            kept = set(sessions[-(seconds // 86_400):])
            return [row for row in visible if row["start"].date() in kept]
        floor = end - timedelta(seconds=seconds)
        return [row for row in visible if row["start"] >= floor]


def _parse_end_stamp(text):
    cleaned = text.replace("  ", " ").strip()
    for fmt in ("%Y%m%d %H:%M:%S", "%Y%m%d-%H:%M:%S", "%Y%m%d"):
        try:
            return datetime.strptime(cleaned, fmt)
        except ValueError:
            continue
    raise AssertionError("unreadable endDateTime %r" % (text,))


