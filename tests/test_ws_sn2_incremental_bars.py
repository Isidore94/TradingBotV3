# ------------------------------------------------------------- the packet's tests


def test_the_frame_built_from_cache_plus_delta_is_identical_to_a_fresh_fetch(monkeypatch):
    """SN2's whole promise: after the first cycle the symbol costs a delta, and
    what the detectors read is still exactly the fresh five-day frame."""
    harness = Harness(monkeypatch)
    harness.cycle(CYCLE_1_NOW)
    harness.cycle(CYCLE_2_NOW)

    assert_frame_equal(harness.frame_for(SYMBOL, 1), golden("intraday_cycle_2"))
    assert harness.bot.latest_bars[SYMBOL] == bounce_bot._dedupe_bars(
        bounce_bot._bars_to_ib(golden("intraday_cycle_2").to_dict(orient="records"))
    ), "the RRS bar cache must carry the same bars as the frame"

    whole_window = [req for req in harness.ib.requests if is_whole_window_request(req)]
    assert len(whole_window) == 1, (
        "the five days must be fetched ONCE per symbol per day; cycle 2 asked "
        "for %s" % ([req.duration for req in harness.ib.requests_in_cycle(1)],)
    )
    assert harness.ib.requests_in_cycle(1)[0].bar_size == "5 mins"


def test_the_day_roll_refetches_the_window_and_the_next_cycle_is_a_delta_again(monkeypatch):
    """A ``5 D`` window slides at the roll - Monday's window has dropped
    Monday-a-week-ago - so the cache cannot be appended to across it.  The roll
    refetches, and the cycle after it is a delta again."""
    harness = Harness(monkeypatch)
    harness.cycle(FRIDAY_LAST_NOW)
    harness.cycle(MONDAY_FIRST_NOW)
    harness.cycle(MONDAY_SECOND_NOW)

    assert any(is_whole_window_request(req) for req in harness.ib.requests_in_cycle(1)), (
        "the first cycle of a new day must refetch the whole window; it asked "
        "for %s" % ([req.duration for req in harness.ib.requests_in_cycle(1)],)
    )
    assert_frame_equal(harness.frame_for(SYMBOL, 1), golden("monday_first"))

    third = harness.ib.requests_in_cycle(2)
    assert third and not any(is_whole_window_request(req) for req in third), (
        "the cycle after the roll must be a delta again, not another five days; "
        "it asked for %s" % ([req.duration for req in third],)
    )
    assert_frame_equal(harness.frame_for(SYMBOL, 2), golden("monday_second"))


def test_a_forming_last_bar_forces_a_whole_window_refetch_and_the_cache_recovers(monkeypatch):
    """The fault the packet names.  A forming bar carries a preview price; a
    delta merged onto it writes that preview into the frame for good.  It must
    force a whole-window refetch, and the cycle after that is a delta again."""
    harness = Harness(monkeypatch)
    harness.ib.serve_forming_bar = True
    harness.cycle(FORMING_NOW)  # cycle 0: the 09:20 bar is still forming
    harness.ib.serve_forming_bar = False

    cached = harness.bot.latest_bars[SYMBOL]
    assert cached[-1].dt == datetime(2026, 6, 5, 9, 20), (
        "the fake must actually have served the forming bar, or this test "
        "proves nothing; last cached bar is %s" % (cached[-1].dt,)
    )

    harness.cycle(CYCLE_3_NOW)  # cycle 1: must NOT merge onto the forming bar
    harness.cycle(CYCLE_4_NOW)  # cycle 2: clean cache, back to a delta

    assert any(is_whole_window_request(req) for req in harness.ib.requests_in_cycle(1)), (
        "a partial last bar in the cache must trigger a whole-window refetch, "
        "never a merge; cycle 1 asked for %s"
        % ([req.duration for req in harness.ib.requests_in_cycle(1)],)
    )
    assert_frame_equal(harness.frame_for(SYMBOL, 1), golden("intraday_cycle_3"))

    third = harness.ib.requests_in_cycle(2)
    assert third and not any(is_whole_window_request(req) for req in third), (
        "after a clean refetch the next cycle must be a delta again; it asked "
        "for %s" % ([req.duration for req in third],)
    )
    assert_frame_equal(harness.frame_for(SYMBOL, 2), golden("intraday_cycle_4"))


def test_a_delta_that_does_not_line_up_with_the_cache_forces_a_whole_window_refetch(monkeypatch):
    """The identity check.  IB revises prints; a revised overlap bar means the
    cache and the delta are not the same series.  The delta request must cover
    the cache's last bar so dt AND close can be compared, and a mismatch must
    throw the cache away rather than splice two different series together."""
    harness = Harness(monkeypatch)
    harness.cycle(CYCLE_1_NOW)

    # 08:55 is the last bar the cache holds; its close is revised behind us.
    harness.series_by_symbol[SYMBOL] = _revised_series()
    harness.cycle(CYCLE_2_NOW)

    second = harness.ib.requests_in_cycle(1)
    assert second, "cycle 2 issued no request"
    assert not is_whole_window_request(second[0]), (
        "cycle 2 must ASK for the delta first - the mismatch is only visible "
        "once the overlap bar comes back; it asked for %s"
        % ([req.duration for req in second],)
    )
    assert duration_seconds(second[0].duration) >= 2 * BAR_MINUTES * 60, (
        "the delta request must reach back over the cache's last bar, or there "
        "is nothing to check the identity against (duration was %r)"
        % (second[0].duration,)
    )
    assert any(is_whole_window_request(req) for req in second), (
        "a mismatched overlap bar must force a whole-window refetch; cycle 2 "
        "only asked for %s" % ([req.duration for req in second],)
    )
    assert_frame_equal(harness.frame_for(SYMBOL, 1), golden("revised_cycle_2"))


def test_after_the_first_cycle_a_symbol_costs_one_delta_request_per_cycle(monkeypatch):
    """The measurement: 1 x "5 D" on the first cycle of the day, then 1 x delta
    a cycle.  ~390 bars a symbol a cycle becomes ~5."""
    harness = Harness(monkeypatch)
    harness.cycle(CYCLE_1_NOW)
    harness.cycle(CYCLE_2_NOW)
    harness.cycle(CYCLE_3_NOW)
    harness.cycle(CYCLE_4_NOW)

    first = harness.ib.requests_in_cycle(0)
    assert len(first) == 1 and first[0].duration == FULL_WINDOW_DURATION
    assert harness.ib.bars_served_in_cycle(0) > 300, (
        "the first cycle of the day is the whole window; it served %s bars"
        % (harness.ib.bars_served_in_cycle(0),)
    )

    for cycle_index in (1, 2, 3):
        requests = harness.ib.requests_in_cycle(cycle_index)
        assert len(requests) == 1, (
            "cycle %s must cost exactly one request per symbol, it made %s (%s)"
            % (cycle_index, len(requests), [req.duration for req in requests])
        )
        assert not is_whole_window_request(requests[0]), (
            "cycle %s refetched the whole five days (%r) instead of the delta"
            % (cycle_index, requests[0].duration)
        )
        served = harness.ib.bars_served_in_cycle(cycle_index)
        assert served <= 12, (
            "a 25-minute cycle is five new 5-minute bars plus an overlap; "
            "cycle %s pulled %s bars" % (cycle_index, served)
        )

    assert_frame_equal(harness.frame_for(SYMBOL, 3), golden("intraday_cycle_4"))


def test_a_symbol_that_leaves_the_scanned_set_frees_its_frame(monkeypatch):
    """~600 symbols x ~390 bars is a bounded cache only while it is bounded BY
    the scanned set.  The cycle-start policy hook is the real seam
    (``_prune_latest_bars_for_cycle``); a symbol it drops must lose its SN2
    frame too, and pay for a whole window when it comes back."""
    harness = Harness(monkeypatch)
    harness.add_symbol(OTHER_SYMBOL)
    harness.cycle(CYCLE_1_NOW, symbols=(SYMBOL, OTHER_SYMBOL))

    assert harness.bot.cached_bounce_frame(OTHER_SYMBOL) is not None, (
        "the first cycle must have retained a frame for %s" % (OTHER_SYMBOL,)
    )

    # A background-keep cycle whose scanned set no longer holds OTHER_SYMBOL.
    harness.bot._prune_latest_bars_for_cycle(False, {SYMBOL})

    assert harness.bot.cached_bounce_frame(OTHER_SYMBOL) is None, (
        "%s left the scanned set; its frame is still held and will never be "
        "freed" % (OTHER_SYMBOL,)
    )
    assert harness.bot.cached_bounce_frame(SYMBOL) is not None, (
        "%s is still scanned; dropping its frame throws away the whole point "
        "of SN2" % (SYMBOL,)
    )

    harness.cycle(CYCLE_2_NOW, symbols=(SYMBOL, OTHER_SYMBOL))
    by_symbol = {}
    for req in harness.ib.requests_in_cycle(1):
        by_symbol.setdefault(req.symbol, []).append(req)
    assert not any(is_whole_window_request(req) for req in by_symbol[SYMBOL]), (
        "the kept symbol must still be a delta; it asked for %s"
        % ([req.duration for req in by_symbol[SYMBOL]],)
    )
    assert any(is_whole_window_request(req) for req in by_symbol[OTHER_SYMBOL]), (
        "the dropped symbol has no frame left and must refetch the window; it "
        "asked for %s" % ([req.duration for req in by_symbol[OTHER_SYMBOL]],)
    )
