def test_a_repeated_night_writes_the_note_lane_tag_once(desk):
    """Item 4: a second run over unchanged evidence is a no-op.

    The bulk tagger's idempotence is what makes it safe to run after every
    scan. A lane that re-proposed its tag every night would append an
    adjustment a night for the life of the journal.
    """
    _write_note(
        desk,
        text=CLAIM_TEXT,
        symbols=["AAPL"],
        written_at=datetime(2026, 9, 11, 10, 15, tzinfo=ET),
    )
    store = _journal(desk, [{"trade_id": "T-ONCE"}])

    _, first = _apply(store)
    assert first["applied"] == 1, "the first night writes the tag"
    second_plan, second = _apply(store)
    assert second["applied"] == 0, "the second night writes nothing"
    assert second_plan.to_apply == [], (
        "an unchanged note produces no new decision to apply"
    )
    assert _slug(_annotation_row(store, "T-ONCE")["setup_tags"]) == CLAIM_SLUG


def test_the_note_lane_reads_no_outcome_field(desk):
    """Item 1 / the tagging rules: no tag may come from what the trade did.

    Two trades identical in every way the lane may look at and opposite in the
    one it may not. The candidates they produce must be the same object, field
    for field, apart from nothing at all.

    The second half is the packet's grep-guard, and it is deliberately a SOURCE
    check: it finds the lane by name and reads its inputs, because a behavioural
    test alone cannot prove a field is unreachable, only that today's fixture
    did not reach it.
    """
    _write_note(
        desk,
        text=CLAIM_TEXT,
        symbols=["AAPL"],
        written_at=datetime(2026, 9, 11, 10, 15, tzinfo=ET),
    )
    store = _journal(
        desk,
        [
            {"trade_id": "T-WIN", "net_pnl": 1450.0},
            {"trade_id": "T-LOSS", "net_pnl": -1450.0},
        ],
    )

    winner = _note_candidates(_suggestions(store, "T-WIN"))
    loser = _note_candidates(_suggestions(store, "T-LOSS"))
    assert winner and loser, "both trades match the same note"
    assert winner == loser, (
        "the note lane's answer cannot move with the trade's P&L"
    )

    # The grep-guard. The lane is found by name rather than by a hardcoded
    # symbol so the builder may call it what it likes, as long as it says note.
    lane_sources = []
    for holder in (journal_analytics, journal_analytics.AutoTagger):
        for name, member in vars(holder).items():
            if "note" not in name.lower() or not callable(member):
                continue
            try:
                lane_sources.append((name, inspect.getsource(member)))
            except (OSError, TypeError):  # pragma: no cover - defensive
                continue
    assert lane_sources, (
        "journal_analytics exposes a note lane whose inputs can be read"
    )
    forbidden = (
        "net_pnl", "realized", "pnl_cad", "mfe", "r_multiple", "exit_price",
        "outcome", "win_rate",
    )
    for name, source in lane_sources:
        for field in forbidden:
            assert field not in source, (
                f"{name} reads {field!r}; no tag may be derived from an outcome"
            )


