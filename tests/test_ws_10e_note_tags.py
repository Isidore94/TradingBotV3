def test_a_claimed_like_in_the_window_outranks_a_note(desk):
    """Item 1: ordering is by LANE. `trader_capture` leads, the note follows.

    The trader claimed one setup on the capture rail and wrote a different one
    in the journal, both inside this trade's window. The rail claim is an
    explicit, structured statement with an event id; the note is prose. The
    rail wins the top slot and the writer takes it.
    """
    _annotation(
        desk,
        event_type="like_claim",
        symbol="AAPL",
        session_date=SESSION,
        side="LONG",
        like_mode="claimed",
        claimed_setup_id=CAPTURE_CLAIM,
    )
    _write_note(
        desk,
        text=CLAIM_TEXT,
        symbols=["AAPL"],
        written_at=datetime(2026, 9, 11, 10, 15, tzinfo=ET),
    )
    store = _journal(desk, [{"trade_id": "T-RANK"}])

    ordered = _suggestions(store, "T-RANK")
    positions = {}
    for index, item in enumerate(ordered):
        if str(item.get("source") or "").startswith(
            f"{journal_analytics.TRADER_CAPTURE_SOURCE}:"
        ):
            positions.setdefault("capture", index)
        elif str(item.get("match_basis") or "").startswith("note:"):
            positions.setdefault("note", index)
    assert "capture" in positions, "the claimed like is still a capture candidate"
    assert "note" in positions, "the note lane still produces its candidate"
    assert positions["capture"] < positions["note"], (
        "a claimed like inside the window outranks a written note"
    )

    _apply(store)
    assert _slug(_annotation_row(store, "T-RANK")["setup_tags"]) == CAPTURE_CLAIM, (
        "the writer takes the trader's structured claim, not the prose one"
    )


