def test_tag_week_marks_the_provisional_tags_that_came_from_a_note(desk, monkeypatch):
    """Item 3: the trader can see WHICH proposals came from their own words.

    Two provisional rows in the same table: one the note lane wrote, one that
    did not come from a note. Exactly one is marked, and it is the note's.
    """
