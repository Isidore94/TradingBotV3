    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    from PySide6.QtWidgets import QApplication

    import project_paths
    from ui.panels import weekend_prep_panel
    from ui.services.weekend_prep_service import WeekendPrepService

    _write_note(
        desk,
        text=CLAIM_TEXT,
        symbols=["AAPL"],
        written_at=datetime(2026, 9, 11, 10, 15, tzinfo=ET),
    )
    store = _journal(
        desk,
        [
            {"trade_id": "T-TW-NOTE", "symbol": "AAPL"},
            {"trade_id": "T-TW-OTHER", "symbol": "MSFT"},
        ],
    )
    _apply(store)
    # The second row's provisional tag comes from somewhere that is not a note,
    # so the marker has something to distinguish itself from.
    assert store.apply_provisional_tags("T-TW-OTHER", "sma_breakout_retest")

    rows = weekend_prep_panel._read_week_tag_rows((SESSION, SESSION), store=store)
    by_id = {str(row.get("trade_id")): row for row in rows}
    assert {"T-TW-NOTE", "T-TW-OTHER"} <= set(by_id), (
        "both provisional rows reach the review list"
    )

    monkeypatch.setattr(
        project_paths, "WEEKEND_PREP_STATE_FILE", desk["tmp"] / "wp.json", raising=False
    )
    application = QApplication.instance() or QApplication([])
    page = weekend_prep_panel.TagWeekPage(WeekendPrepService())
    try:
        page._on_rows_ready({"tags": rows, "missing_risk": [], "coverage": ""})
        application.processEvents()
        rendered = {}
        for index in range(page.table.rowCount()):
            cells = [
                page.table.item(index, column).text()
                if page.table.item(index, column) is not None else ""
                for column in range(page.table.columnCount())
            ]
            line = " | ".join(cells)
            rendered["T-TW-NOTE" if "AAPL" in line else "T-TW-OTHER"] = line.lower()
        assert set(rendered) == {"T-TW-NOTE", "T-TW-OTHER"}
        assert "note" in rendered["T-TW-NOTE"], (
            "the row whose provisional tag came from a journal note is marked"
        )
        assert "note" not in rendered["T-TW-OTHER"], (
            "and a row that did not come from a note is not"
        )
    finally:
        page.shutdown()
        page.deleteLater()
        application.processEvents()
