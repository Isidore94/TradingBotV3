def _widget_text(widget) -> str:
    from PySide6.QtWidgets import QWidget

    texts: list[str] = []
    for child in widget.findChildren(QWidget):
        for getter in ("text", "toPlainText"):
            reader = getattr(child, getter, None)
            if callable(reader):
                try:
                    texts.append(str(reader()))
                except TypeError:
                    pass
    return "\n".join(texts)


