def _write_note(desk, *, text, symbols, written_at: datetime) -> str:
    """One Market Journal entry, through its own builder and a real ledger.

    Returns the `entry_id`. `written_at` is the ACTUAL write time - the field
    the packet's window is measured against - and it is what the ledger also
    derives the row's `session_date` from, so the fixture cannot claim a
    session the write time contradicts.
    """
    import market_journal
    from evidence_ledger import EvidenceLedger, market_session_date

    session = market_session_date(written_at).isoformat()
    entry = market_journal.build_entry(
        text=text,
        session_date=session,
        symbols=symbols,
        origin=market_journal.ORIGIN_DESK_TAB,
        now=written_at,
    )
    ok, reason = market_journal.is_publishable(entry)
    assert ok, reason
    ledger = EvidenceLedger(
        stream=market_journal.STREAM,
        schema=market_journal.SCHEMA_MARKET_JOURNAL_ENTRY,
        directory=desk["ledger_dir"],
    )
    row = ledger.append(entry, now=written_at)
    return str(row["entry_id"])


def _journal(desk, trades):
    """A `JournalStore` holding exactly `trades`, each with an EMPTY annotation.

    An old row has the trader-owned key PRESENT and EMPTY, not absent - which
    is what `apply_provisional_tags`' refusal branch reads.
    """
    from journal_store import JournalStore

    store = JournalStore(desk["tmp"] / "journal.sqlite3")
    with store.connection() as conn:
        for trade in trades:
            conn.execute(
                "INSERT INTO trades(trade_id, broker, account_number, account_label,"
                " symbol, security_type, currency, direction, status, opened_at,"
                " closed_at, trade_date, net_pnl, updated_at)"
                " VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                (
                    trade["trade_id"], "QUESTRADE", "1", "TFSA",
                    trade.get("symbol", "AAPL"), "STK", "USD",
                    trade.get("direction", "LONG"), trade.get("status", "CLOSED"),
                    trade.get("opened_at", OPENED_AT),
                    trade.get("closed_at", CLOSED_AT),
                    trade.get("trade_date", SESSION),
                    trade.get("net_pnl", 125.0), "x",
                ),
            )
            conn.execute(
                "INSERT INTO trade_annotations(trade_id, setup_tags, notes,"
                " updated_at, tag_status) VALUES(?,?,?,?,?)",
                (
                    trade["trade_id"],
                    trade.get("setup_tags", ""),
                    "",
                    "x",
                    trade.get("tag_status", "confirmed"),
                ),
            )
    return store


def _trade_row(store, trade_id: str) -> dict:
    return dict(store.get_trade(trade_id))


def _suggestions(store, trade_id: str) -> list[dict]:
    """What the deterministic tagger says about one trade, in its own order."""
    tagger = journal_analytics.AutoTagger()
    return list(tagger.suggest_for_trade(_trade_row(store, trade_id)))


def _note_candidates(candidates) -> list[dict]:
    return [
        item for item in candidates
        if str(item.get("match_basis") or "").startswith("note:")
    ]


def _annotation(desk, **fields):
    from ui.annotations import store as annotation_store

    row = annotation_store.record_annotation(path=desk["annotations"], **fields)
    assert row is not None, "the annotation fixture did not reach disk"
    return row


def _apply(store):
    plan = journal_bulk_tag.build_plan(store)
    return plan, journal_bulk_tag.apply_plan(store, plan)


def _annotation_row(store, trade_id: str) -> dict:
    with store.connection() as conn:
        row = conn.execute(
            "SELECT setup_tags, tag_status FROM trade_annotations WHERE trade_id = ?",
            (trade_id,),
        ).fetchone()
    return {"setup_tags": row[0], "tag_status": row[1]}


