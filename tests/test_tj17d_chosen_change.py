from PySide6.QtWidgets import QApplication, QPushButton  # noqa: E402


@pytest.fixture(scope="module")
def qapp():
    return QApplication.instance() or QApplication([])


def test_active_idea_row_has_explicit_actions_and_disables_every_new_action_while_writing(qapp):
    """The same row is the write surface on Day and Week Review.

    A real Keep write is held open.  An active row arriving during it must show
    Use/Followed/Did not follow/Not sure/Finish and every one is grey until the
    off-Qt write ends.
    """
    from ui.widgets.ideas_card import IdeasCard

    gate = threading.Event()
    started = threading.Event()

    def writer(_idea_id, _status):
        started.set()
        gate.wait(5.0)

    card = IdeasCard(writer=writer)
    try:
        card.show_ideas([{"idea_id": "a", "kind": "process", "text": "First", "status": ""}])
        card.rows[0].keep_button.click()
        assert started.wait(5.0)
        card.show_ideas(
            [{
                "idea_id": "a",
                "kind": "process",
                "text": "First",
                "status": "kept",
                "current_choice": {"observation_start": NEXT_SESSION, "week": "2026-W39"},
            }]
        )
        labels = {button.text(): button for button in card.findChildren(QPushButton)}
        expected = {"Use this week", "Followed today", "Did not follow", "Not sure", "Finish this change"}
        assert expected <= set(labels)
        assert all(labels[label].isEnabled() is False for label in expected)
    finally:
        gate.set()
        deadline = time.perf_counter() + 5.0
        while card.is_writing() and time.perf_counter() < deadline:
            qapp.processEvents()
            time.sleep(0.01)
        card.shutdown()
        card.deleteLater()
        qapp.processEvents()
