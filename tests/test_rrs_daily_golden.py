# --- fixed synthetic daily bars ------------------------------------------------

DAILY_DAYS = 90
DAILY_START = date(2026, 3, 2)


def business_days(count: int, start: date = DAILY_START) -> list[date]:
    out: list[date] = []
    day = start
    while len(out) < count:
        if day.weekday() < 5:
            out.append(day)
        day += timedelta(days=1)
    return out


def daily_closes() -> dict[str, list[float]]:
    n = DAILY_DAYS
    burst = []
    for i in range(n):
        base = 100.0 + 0.5 * math.sin(i * 1.1)
        burst.append(base + (10.0 if i >= 80 else 0.0))
    return {
        "SPY": [500.0 + 0.25 * i + 1.0 * math.sin(i * 0.7) for i in range(n)],
        "STRONG": [100.0 + 1.0 * i + 0.3 * math.sin(i * 0.9) for i in range(n)],
        "WEAK": [100.0 - 0.6 * i + 0.3 * math.sin(i * 0.8) for i in range(n)],
        "BURST": burst,
        "FLAT": [100.0 + 0.4 * math.sin(i * 1.3) for i in range(n)],
        "XLK": [200.0 + 0.45 * i + 0.5 * math.sin(i * 0.6) for i in range(n)],
        "XLE": [80.0 - 0.25 * i + 0.3 * math.sin(i * 0.5) for i in range(n)],
        # Only the last 28 sessions: too short for a full rolling read.
        "NEWCO": [50.0 + 0.2 * i for i in range(28)],
    }


SPREADS = {"SPY": 1.5, "XLK": 1.0, "XLE": 0.6}


def daily_frame(symbol: str, closes: list[float] | None = None) -> pd.DataFrame:
    closes = closes if closes is not None else daily_closes()[symbol]
    days = business_days(DAILY_DAYS)[-len(closes):]
    spread = SPREADS.get(symbol, 0.8)
    rows = []
    prev = closes[0]
    for i, (day, close) in enumerate(zip(days, closes, strict=True)):
        wiggle = spread * (1.0 + 0.3 * math.sin(i * 0.37))
        rows.append(
            {
                "datetime": pd.Timestamp(day),
                "open": prev,
                "high": max(prev, close) + wiggle,
                "low": min(prev, close) - wiggle,
                "close": close,
                "volume": 1_000_000.0 + 1000.0 * i,
            }
        )
        prev = close
    return pd.DataFrame(rows)


def daily_frames() -> dict[str, pd.DataFrame]:
    return {symbol: daily_frame(symbol) for symbol in daily_closes()}


STOCKS = ("STRONG", "WEAK", "BURST", "FLAT", "NEWCO")
INDUSTRY_OF = {"STRONG": "XLK", "BURST": "XLK", "WEAK": "XLE", "FLAT": "XLE", "NEWCO": "XLK"}


def spy_benchmark(frame: pd.DataFrame) -> dict:
    """The regime snapshot's SPY entry, as ``legacy`` builds it."""
    closes = [float(c) for c in frame["close"]]
    one = (closes[-1] - closes[-2]) / closes[-2] * 100
    five = (closes[-1] - closes[-6]) / closes[-6] * 100
    return {"one_day_return_pct": round(one, 3), "five_day_return_pct": round(five, 3)}


# --- fixed synthetic M5 bars for rs_engine_v1 ----------------------------------

M5_SESSIONS = (date(2026, 7, 6), date(2026, 7, 7), date(2026, 7, 8), date(2026, 7, 9), date(2026, 7, 10))
M5_BARS_PER_SESSION = 78


def m5_closes(symbol: str) -> list[float]:
    out: list[float] = []
    total = len(M5_SESSIONS) * M5_BARS_PER_SESSION
    for k in range(total):
        session, j = divmod(k, M5_BARS_PER_SESSION)
        if symbol == "SPY":
            out.append(500.0 + 0.01 * k + 0.1 * math.sin(k * 0.21))
        elif symbol == "A":  # steady leader
            out.append(100.0 + 0.02 * k + 0.03 * math.sin(k * 0.3))
        elif symbol == "B":  # flat
            out.append(100.0 + 0.03 * math.sin(k * 0.4))
        elif symbol == "C":  # steady laggard
            out.append(100.0 - 0.02 * k + 0.03 * math.sin(k * 0.33))
        elif symbol == "D":  # bursts at the last session's open, then flat
            last = session == len(M5_SESSIONS) - 1
            out.append(100.0 + 0.03 * math.sin(k * 0.4) + (3.0 if last and j >= 2 else 0.0))
        else:
            raise KeyError(symbol)
    return out


def m5_bars(symbol: str):
    from market_state import M5Bar

    closes = m5_closes(symbol)
    bars = []
    prev = closes[0]
    for k, close in enumerate(closes):
        session, j = divmod(k, M5_BARS_PER_SESSION)
        day = M5_SESSIONS[session]
        ts = datetime(day.year, day.month, day.day, 6, 35) + timedelta(minutes=5 * j)
        pad = 0.05 * (1.0 + 0.5 * math.sin(k * 0.17)) * (5.0 if symbol == "SPY" else 1.0)
        bars.append(
            M5Bar(
                ts=ts,
                open=prev,
                high=max(prev, close) + pad,
                low=min(prev, close) - pad,
                close=close,
                volume=100_000.0,
            )
        )
        prev = close
    return bars


