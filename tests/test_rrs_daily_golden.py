def build_golden(tmp_dir: Path) -> dict:
    import setup_playbook_study
    from master_avwap_lib import legacy
    from relative_strength import CandidateInput, RelativeStrengthEngine
    from ui.services import rs_window_feed

    frames = daily_frames()
    spy_frame = frames["SPY"]
    benchmark = spy_benchmark(spy_frame)
    spy_rows = legacy._daily_frame_to_rows(spy_frame)
    out: dict = {"source_commit": PINNED_SOURCE_COMMIT}

    # 1. RS Window daily strength map (d1_rs_5d / d1_rs_20d).
    original_loader = setup_playbook_study._load_daily_frame
    original_dir = legacy.MASTER_AVWAP_DAILY_BARS_DIR
    setup_playbook_study._load_daily_frame = lambda symbol: frames.get(symbol)
    legacy.MASTER_AVWAP_DAILY_BARS_DIR = tmp_dir
    rs_window_feed._daily_strength_cache.clear()
    try:
        strength = rs_window_feed.daily_strength_map(list(STOCKS) + ["XLK", "XLE"])
    finally:
        setup_playbook_study._load_daily_frame = original_loader
        legacy.MASTER_AVWAP_DAILY_BARS_DIR = original_dir
        rs_window_feed._daily_strength_cache.clear()
    out["daily_strength_map"] = {symbol: _clean(strength[symbol]) for symbol in sorted(strength)}

    # 2. Master AVWAP D1 RS vs SPY, per side.
    assess = {}
    for symbol in STOCKS:
        rows = legacy._daily_frame_to_rows(frames[symbol])
        last = date.fromisoformat(rows[-1]["date"])
        for side in ("LONG", "SHORT"):
            result = legacy.assess_daily_relative_strength(
                rows, last, side, benchmark, **_kw(legacy.assess_daily_relative_strength, spy_daily_rows=spy_rows)
            )
            assess[f"{symbol}|{side}"] = _clean(result)
    out["assess_daily"] = assess

    # 3. Universe rows (stock vs SPY and vs its industry ETF), industry ETF rows.
    contexts = {
        symbol: {"sector": "S", "industry": f"I-{INDUSTRY_OF[symbol]}", "industry_etf": INDUSTRY_OF[symbol]}
        for symbol in STOCKS
    }
    industry_frames = {"XLK": frames["XLK"], "XLE": frames["XLE"]}
    universe = legacy.build_universe_strength_rows(
        {symbol: frames[symbol] for symbol in STOCKS},
        benchmark,
        sides_by_symbol={symbol: "LONG" for symbol in STOCKS},
        industry_context_by_symbol=contexts,
        industry_daily_frames_by_etf=industry_frames,
        **_kw(legacy.build_universe_strength_rows, spy_daily_rows=spy_rows),
    )
    out["universe_rows"] = [
        {field: _clean(row.get(field)) for field in UNIVERSE_FIELDS} for row in universe
    ]
    industry = legacy.build_industry_strength_rows(
        industry_frames,
        benchmark,
        industry_context_by_symbol=contexts,
        **_kw(legacy.build_industry_strength_rows, spy_daily_rows=spy_rows),
    )
    out["industry_rows"] = [
        {
            field: _clean(row.get(field))
            for field in ("symbol", "daily_relative_strength_score", "symbol_five_day_return_pct")
        }
        for row in industry
    ]

    # 4. Industry RS bonus on active priority rows, both sides.
    priority = [
        {"symbol": symbol, "side": side, "score": 100.0, "has_favorite_signal": True, "setup_family": "x"}
        for symbol in STOCKS
        for side in ("LONG", "SHORT")
    ]
    legacy.enrich_priority_rows_with_industry_relative_strength(
        priority, universe, industry, scoring_enabled=True
    )
    out["enriched"] = [{field: _clean(row.get(field)) for field in ENRICHED_FIELDS} for row in priority]

    # 5. rs_engine_v1 cohort ranking on fixed M5 bars.
    spy_m5 = m5_bars("SPY")
    candidates = [
        CandidateInput(symbol=name, side_sign=sign, stock_bars=m5_bars(bars), d1_excess_return_pct=d1)
        for name, bars, sign, d1 in ENGINE_CANDIDATES
    ]
    ranks = RelativeStrengthEngine().rank(spy_m5, candidates)
    out["engine"] = [
        {
            "symbol": r.symbol,
            "side_sign": r.side_sign,
            "tier": r.tier,
            "composite": r.composite,
            "percentile": r.percentile,
            "components": _clean(r.components),
            "penalties": _clean(r.penalties),
            "coverage": r.coverage,
            "data_ok": r.data_ok,
            "engine_version": r.engine_version,
        }
        for r in ranks
    ]
    return out


def _assert_same(actual, expected, path="root"):
    if isinstance(expected, dict):
        assert isinstance(actual, dict), path
        assert sorted(actual) == sorted(expected), f"{path}: keys {sorted(actual)} != {sorted(expected)}"
        for key in expected:
            _assert_same(actual[key], expected[key], f"{path}.{key}")
    elif isinstance(expected, list):
        assert isinstance(actual, list) and len(actual) == len(expected), path
        for index, (a, e) in enumerate(zip(actual, expected, strict=True)):
            _assert_same(a, e, f"{path}[{index}]")
    elif isinstance(expected, float) and not isinstance(expected, bool):
        assert isinstance(actual, (int, float)), f"{path}: {actual!r} != {expected!r}"
        assert math.isclose(actual, expected, rel_tol=1e-9, abs_tol=1e-12), f"{path}: {actual!r} != {expected!r}"
    else:
        assert actual == expected, f"{path}: {actual!r} != {expected!r}"


def _fixture() -> dict:
    return json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))


def test_fixture_is_pinned_to_the_pre_rolling_commit():
    assert _fixture()["source_commit"] == PINNED_SOURCE_COMMIT


def test_desk_engine_reproduces_the_golden(tmp_path, monkeypatch):
    monkeypatch.setenv("TRADINGBOTV3_RRS_ENGINE", "desk")
    _assert_same(json.loads(json.dumps(build_golden(tmp_path))), _fixture())


