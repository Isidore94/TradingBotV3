def test_ws_pt4_the_ranked_buckets_are_matched_on_the_key_not_the_display_label(monkeypatch):
    """The real digest prints `Favorite`, not `favorite_setup`.

    `setup_points.RANKED_BUCKETS` holds the row's own bucket keys, so a digest
    that matched on the printed label would rank NOTHING and silently fall back
    to arrival order - the failure this test exists to catch.
    """
    _switch(monkeypatch, True)
    # The best BOUND and the worst points; it leads under the Wilson order, so
    # a ranking that quietly matched nothing would leave it leading.
    weak = _pick(
        "LOW",
        bucket="Favorite",
        family="avwape_retest",
        expected_r=0.0,
        d1_vs_sector=-5.0,
        d1_vs_industry=-5.0,
        raw={
            "expected_r": 0.0,
            "setup_family": "avwape_retest",
            "daily_relative_strength_score": -5.0,
            "hv_level_blocking_count": 3,
        },
    )
    strong = _pick(
        "HIGH",
        bucket="Favorite",
        family="first_dev_hold",
        expected_r=1.0,
        d1_vs_sector=4.0,
        d1_vs_industry=4.0,
        raw={
            "expected_r": 1.0,
            "setup_family": "first_dev_hold",
            "daily_relative_strength_score": 4.0,
            "has_bounce_event_today": True,
        },
    )
    for pick in (weak, strong):
        pick["bucket_key"] = "favorite_setup"
    text = core.render_away_report(_payload(swing_picks=[weak, strong]))
    assert _pick_order(text) == ["HIGH", "LOW"]


