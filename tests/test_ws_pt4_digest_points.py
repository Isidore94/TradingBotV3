def _near(symbol, *, rs, bounce=False):
    return _pick(
        symbol,
        bucket="near_favorite_zone",
        family="first_dev_hold",
        expected_r=0.5,
        d1_vs_sector=rs,
        d1_vs_industry=rs,
        raw={
            "expected_r": 0.5,
            "setup_family": "first_dev_hold",
            "daily_relative_strength_score": rs,
            "has_bounce_event_today": bounce,
            "previous_close": 30.0,
            "atr20": 1.0,
        },
    )


@pytest.mark.parametrize("enabled", [False, True])
def test_ws_pt4_the_near_cap_is_applied_after_the_ranking(monkeypatch, enabled):
    _switch(monkeypatch, enabled)
    near_picks = [
        _near("NA", rs=-4.0),
        _near("NB", rs=4.0, bounce=True),
        _near("NC", rs=0.0),
        _near("ND", rs=3.0, bounce=True),
        _near("NE", rs=-2.0),
    ]
    text = core.render_away_report(_payload(swing_picks=near_picks))
    shown = _pick_order(text)
    assert len(shown) == core.AWAY_REPORT_MAX_NEAR_ROWS
    assert "(+2 more near-favorite rows hidden" in text
    if enabled:
        # What is hidden is the weakest by POINTS, never the best one.
        totals = {p["symbol"]: core.swing_pick_points(p, RECORDS).total for p in near_picks}
        assert shown == sorted(totals, key=lambda s: -totals[s])[:3]
