def _pick_by_symbol(symbol):
    for pick in _picks():
        if pick["symbol"] == symbol:
            return pick
    raise AssertionError(f"no fixture pick {symbol}")


def _switch(monkeypatch, enabled):
    """The ONE seam: `setup_points.rank_enabled`, never a copied settings key."""
    monkeypatch.setattr(setup_points, "rank_enabled", lambda: bool(enabled))
    monkeypatch.setattr(setup_points, "active_weights", dict)


def _pick_order(text):
    """The symbols of the numbered swing lines, in printed order."""
    order = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or not stripped[0].isdigit() or ". " not in stripped:
            continue
        head, rest = stripped.split(". ", 1)
        if not head.isdigit():
            continue
        symbol = rest.split(" ", 1)[0]
        if symbol.isalpha() and symbol.isupper():
            order.append(symbol)
    return order


def _with_order_clause(golden, label):
    """The golden text with the order named on its ONE `Ranked on:` line."""
    lines = golden.splitlines(keepends=True)
    hits = [i for i, line in enumerate(lines) if line.startswith("Ranked on: ")]
    assert len(hits) == 1, "the golden must carry exactly one `Ranked on:` line"
    index = hits[0]
    body = lines[index].rstrip("\n")
    tail = lines[index][len(body):]
    lines[index] = f"{body} | {label}{tail}"
    return "".join(lines)


