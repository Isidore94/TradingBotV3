def test_ws_pt4_switch_off_leaves_the_digest_as_the_golden_pinned_it(monkeypatch):
    """OFF is today's digest, byte for byte, plus the label naming the order.

    The golden was written by the code BEFORE this packet. Every byte of the
    switch-off digest is accounted for here: the only difference the packet
    allows is the ` | order: Wilson bound` clause on the existing `Ranked on:`
    line, which the gate asks the trader to read on the desk.
    """
    _switch(monkeypatch, False)
    text = core.render_away_report(_payload())
    golden = GOLDEN_PATH.read_text(encoding="utf-8")
    assert text == _with_order_clause(golden, "order: Wilson bound")
    # And the pick lines themselves are untouched: same names, same order.
    assert _pick_order(text) == _pick_order(golden)


def test_ws_pt4_switch_on_ranks_the_ranked_buckets_by_points(monkeypatch):
    """ON: favourite / near / high-conviction by total, everything else after."""
    _switch(monkeypatch, False)
    wilson_order = _pick_order(core.render_away_report(_payload()))
    _switch(monkeypatch, True)
    text = core.render_away_report(_payload())
    points_order = _pick_order(text)

    assert "order: points (switch on)" in text
    assert "order: Wilson bound" not in text
    assert sorted(points_order) == sorted(wilson_order), "nothing is dropped or added"
    assert points_order != wilson_order, "the fixture must actually re-order"

    totals = {
        pick["symbol"]: core.swing_pick_points(pick, RECORDS).total for pick in _picks()
    }
    ranked = [
        symbol
        for symbol in points_order
        if _pick_by_symbol(symbol)["bucket"] in setup_points.RANKED_BUCKETS
    ]
    rest = [symbol for symbol in points_order if symbol not in ranked]
    assert ranked == sorted(ranked, key=lambda s: -totals[s])
    assert points_order == ranked + rest, "every other pick comes after the ranked ones"
    # The rest keep the order they had - the Wilson order is the tiebreak.
    assert rest == [symbol for symbol in wilson_order if symbol in rest]


