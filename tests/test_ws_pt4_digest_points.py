"""WS-PT4 - the AWAY digest ranks its swing picks by POINTS when the switch is on.

WISHLIST item 4 (points), block 4, in the trader's words: *"rank the AWAY
digest's swing picks by points too (today it ranks by the family's Wilson
bound)"*. The lead's ruling: the digest ranks by points ONLY when the EXISTING
Points switch (`setup_points.rank_enabled`, local setting
`rank_setups_by_points`, read AT SORT TIME) is on; off keeps today's order
exactly. Same switch, same weights, same `RANKED_BUCKETS` rule as the desk's
setups table - one scorer, two callers.

The golden `tests/fixtures/ws_pt4_away_digest_switch_off.txt` was pinned from
the code BEFORE this packet (a fixture generated by the code it is meant to pin
is a self-portrait), so the switch-off test is a characterization of the whole
digest text and not of the new ordering.
"""

