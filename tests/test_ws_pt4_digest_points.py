def test_ws_pt4_the_digest_total_is_setup_points_score_row_on_the_same_row():
    """The digest scores with the DESK's scorer over the desk's own fields."""
    for pick in _picks():
        entry = RECORDS.get(pick["family"]) or {}
        wins = int(entry.get("wins") or 0)
        losses = int(entry.get("losses") or 0)
        record = core.swing_family_points_record(RECORDS, pick["family"])
        # The same Wilson bound the Wilson ORDER uses, under the same key the
        # desk panel's `family_headline_rows` writes.
        assert record.get("win_rate_lb") == wilson_lower_bound(wins, wins + losses)
        expected = setup_points.score_row(
            pick["raw"],
            side=pick["side"],
            family_record=record,
            d1_vs_sector=pick["d1_vs_sector"],
            d1_vs_industry=pick["d1_vs_industry"],
            weights={},
        )
        assert core.swing_pick_points(pick, RECORDS, weights={}).total == expected.total


