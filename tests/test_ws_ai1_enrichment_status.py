    # The three 2026-09-11 statements are the newest in the file and must all
    # be present.
    for index in range(1, 4):
        assert f"S-OPEN-{index}" in ids
    assert all(str(row.get("row_id") or row.get("statement_id") or "") for row in examples), (
        "every example points back at the row it was read from"
    )


