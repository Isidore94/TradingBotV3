def test_the_enrichment_module_can_reach_nothing_that_writes_a_live_decision():
    """The model writes advice and nothing else - checked by walking the code.

    Wider than the existing guard in
    `tests/test_ai_enrichment_and_policy_draft.py`: the watchlist writer, the
    Focus store, the review policy and the alert paths are named here too,
    because this packet gives the enrichment a new provider call and a new
    write, and a new import is exactly how one of those would arrive.
    """
    import ast

    tree = ast.parse(Path(enrichment.__file__).read_text(encoding="utf-8"))
    imported: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported.add(node.module)

    forbidden = (
        "bounce_bot", "autopilot_core", "master_avwap", "technical_integrity",
        "price_alert", "d1_level_feed", "focus_pick_store", "candidate_registry",
        "review_learning", "regime_pause_focus", "m5_signal_engines",
        "focus_adoption_gate", "journal_bulk_tag",
    )
    for name in imported:
        assert not name.startswith(forbidden), (
            f"the enrichment module reached live decision code: {name}"
        )

    # String constants that could BE a path. Prose is excluded on purpose: the
    # module's own docstring names `review_policy.json` in the sentence that
    # forbids writing it, and a filename has no spaces.
    tokens = [
        node.value for node in ast.walk(tree)
        if isinstance(node, ast.Constant)
        and isinstance(node.value, str)
        and node.value.strip()
        and not any(character.isspace() for character in node.value)
    ]
    for token in tokens:
        assert not token.endswith(
            ("review_policy.json", "longs.txt", "shorts.txt",
             "swinglongs.txt", "shortswings.txt", "focus_auto_picks.json")
        ), f"the enrichment module names {token} as a path"
