def test_a_provider_failure_is_saved_failed_and_the_ledger_status_is_not_ok(
    tmp_path, monkeypatch
):
    """Item 2: a provider/validation failure is a row AND a degraded ledger.

    Today the exception is swallowed into a `failure(s)` suffix and NOTHING is
    written, so the next night's `_trades_for_session` re-reads the trade as
    fresh and the record of the failure lives only in the ledger's prose.
    """
    import ai_summary

    _gate_is_met(monkeypatch)
    store = _journal_with_one_closed_trade(tmp_path / "j.sqlite3")
    monkeypatch.setattr(ai_summary, "local_provider_enabled", lambda: True)
    monkeypatch.setattr(ai_summary, "local_model", lambda tier="medium": "gemma3:12b")

    def _blows_up(**kwargs):
        raise RuntimeError("endpoint refused the connection")

    monkeypatch.setattr(ai_summary, "request_ai_summary", _blows_up)

    result = enrichment.run_journal_enrichment(
        session_date=SESSION, now=NOW, store=store, review_rows=[],
    )

    rows = store.list_ai_enrichment("T-AI1")
    assert len(rows) == 1, "a failure is recorded against the trade it happened to"
    assert rows[0]["status"] == "failed"
    assert "RuntimeError" in str(rows[0].get("reason") or "") or "RuntimeError" in str(
        rows[0].get("error") or ""
    ), "the error CLASS travels, not just a sentence"
    assert "enriched 0, abstained 0, failed 1 of 1" in result["reason"]
    assert result["status"] != "ok", "C > 0 is never OK"


