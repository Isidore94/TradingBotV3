def _provider_returns(monkeypatch, summary, *, model="gemma3:12b"):
    """Point the enrichment's provider seam at a fixed validated response."""
    import ai_summary

    monkeypatch.setattr(ai_summary, "local_provider_enabled", lambda: True)
    monkeypatch.setattr(ai_summary, "local_model", lambda tier="medium": model)
    monkeypatch.setattr(
        ai_summary,
        "request_ai_summary",
        lambda **kwargs: {
            "schema_version": "ai_summary_result_v1",
            "status": "validated",
            "provider": "local",
            "model": model,
            "summary": dict(summary),
        },
    )


