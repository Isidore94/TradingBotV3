def _session_summary_response() -> dict[str, object]:
    """A response that is VALID under `AI_SUMMARY_JSON_SCHEMA`, and only that.

    Shaped the way a real validated night looks: every model-owned section
    present (PRESENT and empty where the model had nothing, never absent), each
    item carrying the three required keys. This is exactly what the live
    provider path can return today, which is the whole point.
    """
    item = {
        "statement": "AVWAP reclaims held into the close on 3 of 4 names.",
        "evidence_refs": ["setups.master_avwap_tier_outcomes"],
        "confidence": "medium",
    }
    return {
        "executive_summary": "A quiet session; the reclaim family carried it.",
        "what_is_working": [item],
        "what_is_not_working": [],
        "best_candidates": [],
        "lessons_for_tomorrow": [],
        "risk_notes": [],
    }


def _validate_against(payload, schema) -> None:
    """A small structural validator - `jsonschema` is not a dependency here.

    Checks exactly the three things that matter for this packet: every
    ``required`` key is present, no key outside ``properties`` is present when
    ``additionalProperties`` is False, and a string ``enum`` is honoured.
    """
    assert isinstance(payload, dict), "a validated response is an object"
    properties = dict(schema.get("properties") or {})
    for key in schema.get("required") or ():
        assert key in payload, f"the schema requires {key!r} and it is absent"
    if schema.get("additionalProperties") is False:
        extra = sorted(set(payload) - set(properties))
        assert not extra, f"keys the schema forbids: {extra}"
    for key, spec in properties.items():
        if key not in payload:
            continue
        allowed = spec.get("enum")
        if allowed is not None:
            assert payload[key] in allowed, (
                f"{key!r}={payload[key]!r} is outside {allowed}"
            )


