def test_a_validated_session_summary_response_enriches_nothing_today():
    """The 10K reproduction, PINNED: the defect, stated as a passing fact.

    A response the live provider path validates and returns carries none of the
    keys the extraction seam reads, so the seam yields an empty summary and no
    tags - which is exactly the six blank rows written over 2026-09-09..11 while
    the ledger said `ok`. This test is expected to pass BEFORE the fix and to
    keep passing after it: the session summary's schema is not the enrichment's,
    and a fix that made this response produce text would be reading the wrong
    document.
    """
    import ai_summary

    response = _session_summary_response()
    _validate_against(response, ai_summary.AI_SUMMARY_JSON_SCHEMA)

    assert enrichment._summary_text(response) == "", (
        "a validated session-summary response has no key the summary extractor reads"
    )
    assert enrichment._proposed_tags(response) == [], (
        "a validated session-summary response has no key the tag extractor reads"
    )


def test_the_enrichment_declares_its_own_schema_the_extractors_can_read():
    """Item 1: the per-trade pass gets its own contract, not the summary's.

    Five fields, `additionalProperties` closed, and - the load-bearing part -
    the keys `_summary_text` and `_proposed_tags` read must be keys this schema
    PERMITS. A schema that forbids them is the defect with a new name.
    """
    import ai_summary

    schema = getattr(enrichment, "ENRICHMENT_JSON_SCHEMA", None)
    assert schema is not None, "the enrichment pass has no schema of its own"
    assert schema is not ai_summary.AI_SUMMARY_JSON_SCHEMA
    assert schema != ai_summary.AI_SUMMARY_JSON_SCHEMA

    properties = dict(schema.get("properties") or {})
    assert set(properties) == {
        "summary", "tags", "confidence", "sources", "unknowns"
    }, "the packet names exactly these five fields"
    assert schema.get("additionalProperties") is False, (
        "an open schema lets the model invent a field the extractors never read"
    )
    assert properties["summary"].get("type") == "string"
    assert properties["tags"].get("type") == "array"
    assert properties["unknowns"].get("type") == "array"
    assert properties["sources"].get("type") == "array"
    assert sorted(properties["confidence"].get("enum") or []) == [
        "high", "low", "medium"
    ]

    # The seam the packet keeps: whatever this schema calls the summary and the
    # tags, the two extractors must be able to reach them.
    assert enrichment._summary_text({"summary": "a sentence"}) == "a sentence"
    assert enrichment._proposed_tags({"tags": ["avwap_reclaim"]}) == ["avwap_reclaim"]


def test_a_response_validated_against_the_enrichment_schema_yields_text_and_tags(
    tmp_path, monkeypatch
):
    """Item 1, through the real `_enrich_one`: text out, vocabulary tags out.

    The response is checked against the enrichment's OWN schema first, so this
    test cannot pass by the model returning something the contract forbids. The
    invented family is dropped and counted - the vocabulary still decides.
    """
    schema = getattr(enrichment, "ENRICHMENT_JSON_SCHEMA", None)
    assert schema is not None, "the enrichment pass has no schema of its own"

    vocabulary = enrichment.setup_vocabulary()
    assert vocabulary, "the setup documents define the vocabulary"
    known = vocabulary[0]

    response = {
        "summary": "Bought the reclaim of the anchored VWAP and held to the close.",
        "tags": [known, "a_family_nobody_defined"],
        "confidence": "medium",
        "sources": ["journal.trade"],
        "unknowns": [],
    }
    _validate_against(response, schema)
    _provider_returns(monkeypatch, response)

    result = enrichment._enrich_one(
        trade={"trade_id": "T-AI1", "symbol": "AAPL", "direction": "LONG",
               "status": "CLOSED", "trade_date": SESSION},
        vocabulary=vocabulary,
        review_rows=[],
        session_date=SESSION,
    )

    assert result["summary"].startswith("Bought the reclaim"), (
        "the enrichment must read the summary its own schema asks for"
    )
    assert result["tags"] == [known]
    assert result["dropped_tags"] == ["a_family_nobody_defined"]
    assert str(result.get("confidence") or "") == "medium"


