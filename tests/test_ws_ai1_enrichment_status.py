def _map_reduce_package(sources):
    """An evidence package shaped the way `plan_chunks` reads one."""
    return {
        "schema_version": "ai_evidence_package_v2",
        "generated_at": f"{SESSION}T20:00:00-07:00",
        "session_date": SESSION,
        "package_id": "pkg0000000000000",
        "evidence_hash": "0" * 64,
        "sources": [
            {"source_id": sid, "label": sid, "status": "available", "content": content}
            for sid, content in sources
        ],
        "coverage": {"counts": {"requested": len(sources), "usable": len(sources),
                                "stale": 0, "truncated": 0}},
    }


def _slice_summary(statement, refs):
    base = {
        name: []
        for name in (
            "what_is_working", "what_is_not_working", "best_candidates",
            "lessons_for_tomorrow", "risk_notes",
        )
    }
    base["executive_summary"] = "a slice"
    base["what_is_working"] = [
        {"statement": statement, "evidence_refs": list(refs), "confidence": "medium"}
    ]
    return base


def test_map_reduce_names_its_completion_when_the_synthesis_falls_back():
    """Item 4: `unsynthesized_fallback` is a WORD in the result, not a flag.

    The 900 s synthesis timeouts on 2026-09-10/11 produced exactly this shape -
    `status: "validated"` with `map_reduce.synthesized = False` - and the only
    reader that could have told them apart was a boolean nested two levels down.
    """
    from ai_jobs import map_reduce

    evidence = _map_reduce_package([("a.one", ["x"]), ("b.two", ["y"])])
    calls = {"n": 0}

    def _map_ok_reduce_times_out(**kwargs):
        calls["n"] += 1
        package = kwargs["evidence"]
        if package["sources"][0]["source_id"] == map_reduce.FINDINGS_SOURCE_ID:
            raise TimeoutError("read timed out after 900s")
        return {"summary": _slice_summary(f"finding {calls['n']}",
                                          [package["sources"][0]["source_id"]])}

    result = map_reduce.run_map_reduce(
        evidence=evidence, model="m", chars=10, request=_map_ok_reduce_times_out,
    )

    assert result["map_reduce"]["synthesized"] is False
    assert result.get("completion") == "unsynthesized_fallback", (
        "a reader must not have to infer the completion from a nested boolean"
    )


def test_map_reduce_names_a_partial_read_when_a_slice_fails():
    """Item 4: some slices lost is `partial`, not `synthesized`."""
    from ai_jobs import map_reduce

    evidence = _map_reduce_package([("a.one", ["x"]), ("b.two", ["y"])])

    def _one_slice_dies(**kwargs):
        package = kwargs["evidence"]
        sid = package["sources"][0]["source_id"]
        if sid == "b.two":
            raise RuntimeError("slice refused")
        return {"summary": _slice_summary("finding", [sid])}

    result = map_reduce.run_map_reduce(
        evidence=evidence, model="m", chars=10, request=_one_slice_dies,
    )

    assert result["map_reduce"]["slices_failed"], "one slice really did fail"
    assert result.get("completion") == "partial"


def test_map_reduce_says_synthesized_when_nothing_was_lost():
    """Item 4: the happy path names itself too, so "" is never the answer."""
    from ai_jobs import map_reduce

    evidence = _map_reduce_package([("a.one", ["x"]), ("b.two", ["y"])])

    def _all_fine(**kwargs):
        package = kwargs["evidence"]
        return {"summary": _slice_summary("finding",
                                          [package["sources"][0]["source_id"]])}

    result = map_reduce.run_map_reduce(
        evidence=evidence, model="m", chars=10, request=_all_fine,
    )

    assert result["map_reduce"]["synthesized"] is True
    assert result.get("completion") == "synthesized"


