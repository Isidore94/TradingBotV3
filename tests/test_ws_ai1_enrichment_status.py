def test_a_legacy_blank_row_is_superseded_once_and_only_once_in_a_night(
    tmp_path, monkeypatch
):
    """Item 3: the six blank rows are repairable, and the retry is bounded.

    The legacy row is modelled the way the live table holds it - `summary` and
    `tags` PRESENT and EMPTY, `status` absent - because that is what six nights
    of the current code wrote. `_trades_for_session` must stop reading it as
    done; the repair appends a new row naming the one it replaces; and a second
    firing of the same night must not append a third.
    """
    _gate_is_met(monkeypatch)
    store = _journal_with_one_closed_trade(tmp_path / "j.sqlite3")
    store.save_ai_enrichment(
        trade_id="T-AI1", session_date=SESSION, summary="", tags=[], evidence=[],
        model="gemma3:12b", now="2026-09-12T02:00:00+00:00",
    )
    legacy = store.list_ai_enrichment("T-AI1")
    assert len(legacy) == 1 and legacy[0]["summary"] == "" and legacy[0]["tags"] == ""
    assert not str(legacy[0].get("status") or ""), "the legacy blank carries no status"
    legacy_id = legacy[0]["enrichment_id"]

    assert enrichment._trades_for_session(store, SESSION), (
        "a blank row is not a finished trade"
    )

    known = enrichment.setup_vocabulary()[0]
    _provider_returns(
        monkeypatch,
        {
            "summary": "Held the reclaim into the close.",
            "tags": [known],
            "confidence": "high",
            "sources": ["journal.trade"],
            "unknowns": [],
        },
    )

    first = enrichment.run_journal_enrichment(
        session_date=SESSION, now=NOW, store=store, review_rows=[],
    )
    assert first["status"] == "ok"

    rows = store.list_ai_enrichment("T-AI1")
    assert len(rows) == 2, "append-only: the blank row is superseded, never rewritten"
    assert rows[0]["summary"] == "", "history is kept"
    assert rows[1]["summary"] == "Held the reclaim into the close."
    assert str(rows[1].get("supersedes_row_id") or "") == str(legacy_id)

    # One retry per night per trade: firing the slot again in the same window
    # must find the trade done and add nothing.
    second = enrichment.run_journal_enrichment(
        session_date=SESSION, now=NOW, store=store, review_rows=[],
    )
    assert len(store.list_ai_enrichment("T-AI1")) == 2, (
        f"a second firing wrote another row ({second['reason']})"
    )


