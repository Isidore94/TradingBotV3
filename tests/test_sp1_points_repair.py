def _logged(scan_date: str, symbol: str, side: str, total: float, **parts: float) -> dict:
    row = {
        "scan_date": scan_date,
        "symbol": symbol,
        "side": side,
        "total": total,
        "setup": 0.0,
        "sr": 0.0,
        "rs": 0.0,
        "bounce": 0.0,
        "bucket": "favorite_setup",
    }
    row.update(parts)
    return row


def test_base_v1_golden_records_the_old_clean_path_mistake():
    """The pre-repair fixture is data, not a result generated by the scorer."""
    fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
    points = setup_points.score_row(fixture["report_row"], side="LONG")

    assert points.sr == fixture["v1_expected"]["sr"]
    assert points.total == fixture["v1_expected"]["total"]
    assert fixture["v1_expected"]["note_absent"] not in points.notes


