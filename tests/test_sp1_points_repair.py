def _logged(scan_date: str, symbol: str, side: str, total: float, **parts: float) -> dict:
    row = {
        "scan_date": scan_date,
        "symbol": symbol,
        "side": side,
        "total": total,
        "setup": 0.0,
        "sr": 0.0,
        "rs": 0.0,
        "bounce": 0.0,
        "bucket": "favorite_setup",
    }
    row.update(parts)
    return row


