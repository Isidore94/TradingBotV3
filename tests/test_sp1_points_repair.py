def test_priority_report_row_uses_matching_cached_rich_scan_before_the_model_scores_it(tmp_path):
    """Drive priority report -> rich cached scan -> model, including identity guards."""
    from ui.models.setup_table_model import SetupTableModel
    from ui.services.data_feed import (
        enrich_report_rows_with_cached_scan,
        load_setup_rows_from_priority_report,
        rows_from_run_result,
    )

    report = tmp_path / "priority.txt"
    report.write_text(
        "Generated at 2026-09-18 20:00 PT scan_stamp=run-18\n"
        "Overall score rankings\n"
        "----------------------\n"
        "  1. NVDA LONG score=88 bucket=Favorite setup family=earnings gap zone=VWAP to UPPER_1\n\n"
        "Ranked by Expected-R (blended)\n"
        "------------------------------\n"
        "NVDA LONG ExpR=+0.00R score=88 family=earnings gap bucket=favorite_setup\n",
        encoding="utf-8",
    )

    report_rows = load_setup_rows_from_priority_report(report)
    rich_rows = rows_from_run_result(
        {
            "tracked_rows": [
                {
                    "symbol": "NVDA", "side": "LONG", "priority_bucket": "favorite_setup",
                    "setup_family": "earnings gap", "scan_date": "2026-09-18", "scan_stamp": "run-18",
                    "scan_row_state": "completed", "sr_inputs_measured": True,
                    "hv_level_blocking_count": 1, "hv_level_nearby_count": 0,
                    "cloud_level_nearby_count": 0, "trendline_in_play": False,
                    "previous_close": 100.0, "atr20": 2.0, "ema21": 90.0,
                    "sma_breakout_sma_level": 90.0, "hv_level_nearest_distance_atr": 1.5,
                },
                # Same symbol but each guard below must reject this candidate.
                {"symbol": "NVDA", "side": "SHORT", "scan_date": "2026-09-18", "scan_stamp": "run-18", "scan_row_state": "completed", "hv_level_blocking_count": 9},
                {"symbol": "NVDA", "side": "LONG", "scan_date": "2026-09-18", "scan_stamp": "run-18", "scan_row_state": "forming", "hv_level_blocking_count": 9},
                {"symbol": "NVDA", "side": "LONG", "scan_date": "2026-09-19", "scan_stamp": "run-19", "scan_row_state": "completed", "hv_level_blocking_count": 9},
            ]
        }
    )
    row = enrich_report_rows_with_cached_scan(report_rows, rich_rows)[0]
    points = SetupTableModel([row]).points_for(row)

    assert row.raw["scan_stamp"] == "run-18"
    assert row.raw["hv_level_blocking_count"] == 1
    assert points.sr == 6.0


