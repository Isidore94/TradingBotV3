def test_claimed_long_and_short_same_symbol_overlay_only_matching_rich_analysis():
    from ui.services.claimed_setup_rows import merge_claims

    claims = [
        {"symbol": "NVDA", "side": "LONG", "claimed_setup_id": "alpha", "claim_at": "2026-09-18T15:00:00Z"},
        {"symbol": "NVDA", "side": "SHORT", "claimed_setup_id": "beta", "claim_at": "2026-09-18T15:01:00Z"},
    ]
    rows = merge_claims(
        [],
        claims,
        analysis_by_identity={
            ("NVDA", "LONG"): {"expected_r": 1.0, "scan_stamp": "run-long", "side": "LONG"},
            ("NVDA", "SHORT"): {"expected_r": -1.0, "scan_stamp": "run-short", "side": "SHORT"},
        },
    )

    by_side = {row.side: row.raw for row in rows}
    assert by_side["LONG"]["expected_r"] == 1.0
    assert by_side["LONG"]["scan_stamp"] == "run-long"
    assert by_side["SHORT"]["expected_r"] == -1.0
    assert by_side["SHORT"]["scan_stamp"] == "run-short"


def test_points_log_keeps_same_day_input_revision_and_dedupes_only_the_identical_snapshot(tmp_path):
    path = tmp_path / "points.jsonl"
    first = _logged("2026-09-18", "NVDA", "LONG", 10.0, sr=0.0)
    first.update({"snapshot_id": "one", "scan_stamp": "run-a", "points_version": "points_v2"})
    revised = _logged("2026-09-18", "NVDA", "LONG", 6.0, sr=-4.0)
    revised.update({"snapshot_id": "two", "scan_stamp": "run-b", "points_version": "points_v2"})

    assert evidence.append_log(path, [first, revised, dict(revised)]) == 2
    logged = evidence.read_log(path)
    assert [(row["snapshot_id"], row["total"], row["scan_stamp"]) for row in logged] == [
        ("one", 10.0, "run-a"),
        ("two", 6.0, "run-b"),
    ]


def test_points_grade_uses_one_pre_close_v2_observation_and_exact_session_outcomes(tmp_path):
    from swing_evidence import OUTCOME_KIND_SESSION_V2

    before_close = _logged("2026-09-18", "NVDA", "LONG", 10.0)
    before_close.update(
        {
            "points_version": "points_v2",
            "snapshot_id": "before-close",
            "observed_at": "2026-09-18T19:00:00+00:00",
        }
    )
    post_close = dict(before_close, snapshot_id="after-close", total=2.0, observed_at="2026-09-19T01:00:00+00:00")
    outcome = tmp_path / "session_outcomes.csv"
    outcome.write_text(
        "observation_id,scan_date,target_session,horizon_sessions,symbol,side,favorable,measured,maturity,outcome_kind\n"
        f"one,2026-09-18,2026-09-25,5,NVDA,LONG,True,True,mature,{OUTCOME_KIND_SESSION_V2}\n",
        encoding="utf-8",
    )

    result = evidence.log_and_grade(
        [before_close, post_close],
        log_path=tmp_path / "points.jsonl",
        weights_path=tmp_path / "weights.json",
        outcomes_path=outcome,
    )

    assert result.n_joined == 1
    assert result.outcome_policy == "favorable_direction_session_v2"
    assert result.horizon_sessions == 5
    assert "directional" in result.sentence().lower()


def test_equal_point_ties_and_session_concentration_abstain_from_a_weight_proposal():
    log_rows = []
    outcome_rows = []
    for index in range(60):
        symbol = f"T{index:03d}"
        log_rows.append(_logged("2026-09-18", symbol, "LONG", 10.0, sr=10.0, bounce=0.0))
        outcome_rows.append({"scan_date": "2026-09-18", "symbol": symbol, "side": "LONG", "win": index < 30})

    result = evidence.grade(log_rows, outcome_rows, horizon_sessions=5)
    proposal = evidence.propose_weights(result)

    assert result.lift is None
    assert set(proposal["multipliers"].values()) == {1.0}
    assert "distinct entry sessions" in " ".join(proposal["reasons"].values())
